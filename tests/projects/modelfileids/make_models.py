#!/usr/bin/env python3
"""Writes Assets/Models/Nested.fbx and Single.fbx: ASCII FBX 7.4 files whose node hierarchy covers
what the IDs of imported objects depend on (see README.md).

    python3 tests/projects/modelfileids/make_models.py
"""
from pathlib import Path

PROBE = Path(__file__).resolve().parent
MODELS = PROBE/'Assets/Models'

CORNERS = [(x, y, z) for z in (-0.5, 0.5) for y in (-0.5, 0.5) for x in (-0.5, 0.5)]
QUADS = [(0, 2, 3, 1), (4, 5, 7, 6), (0, 1, 5, 4), (2, 6, 7, 3), (0, 4, 6, 2), (1, 3, 7, 5)]

# (node, parent or None for the file's top level, has a mesh). Two nodes named Leaf under one
# parent, a mesh three levels down, a mesh under an empty node and two LOD levels.
NESTED = [
    ('Body', None, True),
    ('Arm', 'Body', True),
    ('Hand', 'Arm', True),
    ('Leaf', 'Body', True),
    ('Leaf', 'Body', True),
    ('Empty', None, False),
    ('Deep', 'Empty', True),
    ('Tree_LOD0', None, True),
    ('Tree_LOD1', None, True),
]
# A file with one mesh node at its top level: the node becomes the root.
SINGLE = [('Only', None, True)]


def fmt(v):
    return repr(float(v)) if isinstance(v, float) else str(v)


def write(path, nodes):
    ids = iter(range(200000, 1000000))
    objects, connections = [], []
    material = next(ids)
    objects.append(f'''\tMaterial: {material}, "Material::M_Probe", "" {{
\t\tVersion: 102
\t\tShadingModel: "lambert"
\t\tMultiLayer: 0
\t\tProperties70:  {{
\t\t\tP: "DiffuseColor", "Color", "", "A",0.8,0.8,0.8
\t\t}}
\t}}''')
    vertices = ','.join(fmt(c) for corner in CORNERS for c in corner)
    indices = ','.join(str(i if k < 3 else -i - 1) for quad in QUADS for k, i in enumerate(quad))
    node_ids = []
    for index, (name, parent, mesh) in enumerate(nodes):
        mid = next(ids)
        node_ids.append(mid)
        objects.append(f'''\tModel: {mid}, "Model::{name}", "{'Mesh' if mesh else 'Null'}" {{
\t\tVersion: 232
\t\tProperties70:  {{
\t\t\tP: "Lcl Translation", "Lcl Translation", "", "A",{fmt(1.5 * index)},0,0
\t\t}}
\t\tShading: T
\t\tCulling: "CullingOff"
\t}}''')
        parent_id = 0 if parent is None else next(
            node_ids[i] for i, (n, _, _) in enumerate(nodes[:index]) if n == parent)
        connections.append(f'\tC: "OO",{mid},{parent_id}')
        if mesh:
            gid = next(ids)
            objects.append(f'''\tGeometry: {gid}, "Geometry::{name}", "Mesh" {{
\t\tVertices: *{len(CORNERS) * 3} {{
\t\t\ta: {vertices}
\t\t}}
\t\tPolygonVertexIndex: *24 {{
\t\t\ta: {indices}
\t\t}}
\t\tGeometryVersion: 124
\t\tLayerElementMaterial: 0 {{
\t\t\tVersion: 101
\t\t\tName: ""
\t\t\tMappingInformationType: "AllSame"
\t\t\tReferenceInformationType: "IndexToDirect"
\t\t\tMaterials: *1 {{
\t\t\t\ta: 0
\t\t\t}}
\t\t}}
\t\tLayer: 0 {{
\t\t\tVersion: 100
\t\t\tLayerElement:  {{
\t\t\t\tType: "LayerElementMaterial"
\t\t\t\tTypedIndex: 0
\t\t\t}}
\t\t}}
\t}}''')
            connections += [f'\tC: "OO",{gid},{mid}', f'\tC: "OO",{material},{mid}']
    meshes = sum(1 for n in nodes if n[2])
    counts = {'Model': len(nodes), 'Geometry': meshes, 'Material': 1}
    definitions = '\n'.join(f'\tObjectType: "{k}" {{\n\t\tCount: {v}\n\t}}' for k, v in counts.items())
    path.write_text(f'''; FBX 7.4.0 project file
; Generated by tests/projects/modelfileids/make_models.py
FBXHeaderExtension:  {{
\tFBXHeaderVersion: 1003
\tFBXVersion: 7400
\tCreator: "Unbound model file id probe"
}}
GlobalSettings:  {{
\tVersion: 1000
\tProperties70:  {{
\t\tP: "UpAxis", "int", "Integer", "",1
\t\tP: "UpAxisSign", "int", "Integer", "",1
\t\tP: "FrontAxis", "int", "Integer", "",2
\t\tP: "FrontAxisSign", "int", "Integer", "",1
\t\tP: "CoordAxis", "int", "Integer", "",0
\t\tP: "CoordAxisSign", "int", "Integer", "",1
\t\tP: "UnitScaleFactor", "double", "Number", "",100
\t}}
}}
Definitions:  {{
\tVersion: 100
\tCount: {sum(counts.values())}
{definitions}
}}
Objects:  {{
{chr(10).join(objects)}
}}
Connections:  {{
{chr(10).join(connections)}
}}
''')
    print('wrote', path)


if __name__ == '__main__':
    write(MODELS/'Nested.fbx', NESTED)
    write(MODELS/'Single.fbx', SINGLE)
    # Copies with other metas (README.md): NamedTable.fbx, OldMeta.fbx and OldMetaGen2.fbx.
    for copy in ('NamedTable', 'OldMeta', 'OldMetaGen2'):
        (MODELS/f'{copy}.fbx').write_text((MODELS/'Nested.fbx').read_text())
