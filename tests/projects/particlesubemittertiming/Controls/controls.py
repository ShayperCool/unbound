def write_rows(path, rows):
    path.write_text(''.join(json.dumps(r, separators=(',', ':'))+'\n' for r in rows))


def record_controls(normal, out):
    base = guards.parse(normal)[0]
    work = out/'record-controls'
    work.mkdir()

    def index(key):
        return next(i for i, r in enumerate(base) if r['k'] == key)

    def mutated(name, change, expect):
        rows = copy.deepcopy(base)
        text = change(rows)
        path = work/(re.sub(r'\W+', '-', name)+'.jsonl')
        if isinstance(text, str):
            path.write_text(text)
        else:
            write_rows(path, rows)
        problems = guards.record_problems(path, RELEASE, DEVICE)
        control('record refused: '+name, expect, problems[:4], any(expect in p for p in problems))

    def setv(key, value):
        def change(rows):
            rows[index(key)]['v'] = value
        return change

    def edit(key, change):
        def apply(rows):
            change(rows[index(key)]['v'])
        return apply
    full = normal.read_text()
    mutated('completion-only', lambda rows: '{"k":"complete","v":true}\n', 'missing context.unityVersion')
    mutated('truncated by lines', lambda rows: ''.join(full.splitlines(True)[:len(base)*2//3]), 'completion marker is not the last line')
    mutated('truncated mid-line', lambda rows: full[:len(full)//2], 'truncated')
    mutated('omitted case', lambda rows: rows.__setitem__(slice(None), [r for r in rows if not r['k'].startswith('case.d3')]), 'missing case.d3')
    mutated('omitted snapshot', lambda rows: rows.pop(index('case.d1.death.after2')), 'missing case.d1.death.after2')
    mutated('omitted Birth record', lambda rows: rows.pop(index('case.birth.child.7')), 'missing case.birth.child.7')
    mutated('omitted clocks', lambda rows: rows.pop(index('case.fixed.clock.before')), 'missing case.fixed.clock.before')
    mutated('omitted block log', lambda rows: rows.pop(index('phase.d3.log')), 'missing phase.d3.log')
    mutated('duplicate key', lambda rows: rows.insert(index('case.d2.log'), dict(rows[index('case.d2.log')-1])), 'duplicate key')
    mutated('reordered snapshots', lambda rows: rows.insert(index('case.d1.parent.after1'), rows.pop(index('case.d1.death.after1'))), 'unexpected record')
    mutated('wrong type (count as text)', edit('case.d2.death.after1', lambda v: v.__setitem__('count', '1')), 'case.d2.death.after1: wrong type')
    mutated('particle field missing', edit('case.baseline.ordinary.after1', lambda v: v['particles'][0].pop('seed')), 'wrong type')
    mutated('readCount and particles disagree', edit('case.baseline.parent.before', lambda v: v.__setitem__('readCount', 2)), 'wrong type')
    mutated('clock key missing', edit('clock.startup.clocks', lambda v: v.pop('captureDeltaTime')), 'clock.startup.clocks: wrong type')
    mutated('authored input changed', edit('case.d1.input', lambda v: v.__setitem__('callDelta', 0.036)), 'case.d1.input: wrong type or authored input')
    mutated('phase setting changed', edit('phase.fixed.set', lambda v: v.__setitem__('fixedDeltaTime', 0.01)), 'phase.fixed.set: wrong type or authored input')
    mutated('case read in another frame', edit('case.d3.clock.before', lambda v: v.__setitem__('frameOffset', 3)), 'relative frame 3, not the predeclared 2')
    mutated('fatal record', lambda rows: rows.insert(len(rows)-1, {'k': 'fatal', 'v': 'boom'}), 'fatal')
    mutated('two markers', lambda rows: rows.insert(5, {'k': 'complete', 'v': True}), '2 completion markers')
    mutated('marker not last', lambda rows: rows.append(rows.pop(-2)), 'completion marker is not the last line')
    mutated('extra key', lambda rows: rows.insert(index('case.birth.log'), {'k': 'case.birth.extra', 'v': 1}), 'unexpected record case.birth.extra')
    mutated('probe fault', lambda rows: rows.insert(index('case.d2.log'), {'k': 'case.d2.exception', 'v': 'NullReferenceException: x'}), 'probe fault in block case.d2')
    mutated('wrong release', setv('context.unityVersion', '6000.0.70f1'), 'context.unityVersion')
    mutated('wrong device', setv('context.graphicsDeviceType', 'Null'), 'context.graphicsDeviceType')
    mutated('not batchmode', setv('context.isBatchMode', False), 'context.isBatchMode')
    mutated('unscoped error', setv('capture.unscopedLogs', ['Error: boom']), 'unexpected errors outside the probe cases')
    mutated('not a k/v record', lambda rows: full.replace('{"k":"case.birth.log"', '{"key":"case.birth.log"', 1), 'not a {"k","v"} record')
    # Answers are data: values that contradict every hypothesis still pass the schema guard.
    rows = copy.deepcopy(base)
    for r in rows:
        if r['k'].startswith('case.') and r['k'].endswith('.after1') and isinstance(r['v'], dict):
            r['v']['count'] = 0
            r['v']['readCount'] = 0
            r['v']['particles'] = []
        if r['k'] == 'phase.d3.readback':
            r['v']['captureDeltaTime'] = 0.05
            r['v']['timeScale'] = 1
    path = work/'answers-are-data.jsonl'
    write_rows(path, rows)
    problems = guards.record_problems(path, RELEASE, DEVICE)
    control('record accepted: any count/particle/clock answer (answers never gate)', [], problems, not problems)


