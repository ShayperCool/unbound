def fake_preflight(path, passed=True, sources=None):
    record = {'passed': passed, 'release': RELEASE,
              'sources': sources or {s: sha(PROBE/s) for s in run.SOURCES},
              'results': {a: {'rsp': {'rebound_text': f'-target:library\n-out:"Library/Bee/artifacts/2400b0aE.dag/{a}.dll"\n'
                                                       f'-define:UNITY_6000\n"{preflight.SOURCES[a][0]}"\n'},
                              'rsp2': {'rebound_text': ''}} for a in preflight.SOURCES}}
    path.write_text(json.dumps(record))
    return record


def fake_graph(project, record, dag='2400b0aE.dag', change=None):
    root = Path(project)/'Library/Bee/artifacts'/dag
    root.mkdir(parents=True, exist_ok=True)
    for a, r in record['results'].items():
        text = r['rsp']['rebound_text'].replace('2400b0aE.dag', dag)
        (root/f'{a}.rsp').write_text(change(a, text) if change else text)
        (root/f'{a}.rsp2').write_text(r['rsp2']['rebound_text'])
        (root/f'{a}.UnityAdditionalFile.txt').write_text(str(Path(project).resolve()))


def pair_controls(normal_dir, out):
    work = out/'pair-controls'
    good = work/'preflight-good.json'
    work.mkdir(parents=True)
    record = fake_preflight(good)

    def pair(name, change=None):
        root = work/name
        for repeat in run.REPEATS:
            synthetic_capture(root/repeat, normal_dir, PROBE)
            project = root/'projects'/repeat
            for part in ('Assets', 'Packages', 'ProjectSettings'):
                shutil.copytree(PROBE/part, project/part)
            fake_graph(project, record)
            inputs = json.loads((root/repeat/'inputs.json').read_text())
            inputs.update(preflight=str(good), preflight_sha256=sha(good),
                          tools={n: sha(PROBE/n) for n in run.TOOLS}, sources={s: sha(PROBE/s) for s in run.SOURCES})
            (root/repeat/'inputs.json').write_text(json.dumps(inputs))
        if change:
            change(root)
        return root

    def publish(root, target):
        with mock.patch.object(run, 'reference_file', lambda probe, suffix: target), \
                contextlib.redirect_stdout(io.StringIO()):
            try:
                return run.publish(root, RELEASE), None
            except SystemExit as error:
                return None, str(error)
    root = pair('agree')
    target = work/'agree-reference/unity-6000.0.71f1.jsonl'
    code, refusal = publish(root, target)
    control('pair: two complete agreeing repeats publish (positive, private target)', 'published',
            refusal or 'published', code == 0 and target.read_bytes() == (root/'native1/capture/values.jsonl').read_bytes())
    code, refusal = publish(root, target)
    control('pair refused: existing reference is never overwritten', 'refusing to overwrite', refusal,
            refusal and 'refusing to overwrite' in refusal)

    def disagree(root):
        path = root/'native2/capture/values.jsonl'
        rows = guards.parse(path)[0]
        for r in rows:
            if r['k'] == 'case.d1.death.after1':
                r['v']['time'] = 0.5
        write_rows(path, rows)
    root = pair('disagree', disagree)
    code, refusal = publish(root, work/'disagree-reference.jsonl')
    control('pair refused: disagreeing repeats', 'the repeats differ', refusal,
            refusal and 'the repeats differ' in refusal and not (work/'disagree-reference.jsonl').exists())
    root = pair('one-forced', lambda root: (root/'native2/editor-run.json').write_text(
        (root/'native2/editor-run.json').read_text().replace('"forced_exit": null', '"forced_exit": "shutdown-guard"')))
    code, refusal = publish(root, work/'forced-reference.jsonl')
    control('pair refused: one repeat with a forced (shutdown-guard) exit', 'native2: ... forced exit', refusal,
            refusal and refusal.startswith('native2') and 'forced exit' in refusal)
    root = pair('graph-differs', lambda root: fake_graph(root/'projects/native2', record,
                                                          change=lambda a, t: t.replace('-define:UNITY_6000', '-define:UNITY_6000\n-define:EXTRA')))
    code, refusal = publish(root, work/'graph-reference.jsonl')
    control('pair refused: a repeat compiled another graph than the preflight', 'graph: ... differs', refusal,
            refusal and refusal.startswith('native2') and 'differs from the preflight-compiled graph' in refusal)

    # The graph check alone.
    project = work/'graph/project'
    fake_graph(project, record, dag='99999999.dag')
    problems = guards.graph_problems(project, record)
    control('graph: the same response files under another graph directory name pass', [], problems, not problems)
    for name, mutate, expect in (
            ('another source', lambda a, t: t.replace('SubEmitterTimingProbe.cs', 'Other.cs'), 'differs from the preflight'),
            ('another reference', lambda a, t: t+'-r:"/x/UnityEngine.Extra.dll"\n', 'differs from the preflight'),
            ('another analyzer', lambda a, t: t+'-analyzer:"/x/gen.dll"\n', 'differs from the preflight')):
        p = work/'graph'/re.sub(r'\W+', '-', name)
        fake_graph(p, record, change=mutate)
        problems = guards.graph_problems(p, record)
        control('graph refused: '+name, expect, problems[:3], any(expect in x for x in problems))
    p = work/'graph/elsewhere'
    fake_graph(p, record)
    (p/'Library/Bee/artifacts/2400b0aE.dag/Assembly-CSharp.UnityAdditionalFile.txt').write_text('/elsewhere')
    problems = guards.graph_problems(p, record)
    control('graph refused: additional file names another project', 'does not name the launched copy', problems[:3],
            any('does not name the launched copy' in x for x in problems))
    p = work/'graph/none'
    p.mkdir(parents=True)
    problems = guards.graph_problems(p, record)
    control('graph refused: no Editor-written graph', '0 Bee graph directories', problems[:3], any('0 Bee graph' in x for x in problems))

    # Launch admission: no Editor may start in these cases.
    def no_launch(job):
        raise AssertionError('an Editor launch was attempted')
    bad = work/'preflight-bad.json'
    fake_preflight(bad, passed=False)
    stale = work/'preflight-stale.json'
    fake_preflight(stale, sources={s: '0'*64 for s in run.SOURCES})

    def admit(name, root, repeat, preflight_path, expect):
        with mock.patch.object(run, 'run', no_launch), contextlib.redirect_stdout(io.StringIO()):
            try:
                run.editor(root, repeat, RELEASE, preflight_path)
                outcome = 'started'
            except SystemExit as error:
                outcome = str(error)
            except AssertionError as error:
                outcome = 'LAUNCHED: '+str(error)
        control('admission refused: '+name, expect, outcome, expect in outcome)
    admit('failed preflight', work/'admit-a', 'native1', bad, 'the preflight did not pass')
    admit('stale preflight sources', work/'admit-b', 'native1', stale, 'differs from the preflight-compiled bytes')
