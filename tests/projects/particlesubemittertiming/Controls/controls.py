def source_guards():
    probe = SCRIPTS[0].read_text()
    runner = SCRIPTS[1].read_text()
    code = re.sub(r'//[^\n]*', '', probe)
    cases = dict((k, (float(a), float(b))) for k, a, b in re.findall(r'DeathCase\("(case\.\w+)", ([\d.]+)f, ([\d.]+)f\)', code))
    later = re.findall(r'Later\("(case\.\w+)"', code)
    later_args = re.findall(r'bool ok = DeathCase\(key, ([\d.]+)f, ([\d.]+)f\);', code)
    for key in later:
        cases[key] = tuple(float(x) for x in later_args[0]) if len(later_args) == 1 else None
    want = {k: v[:2] for k, v in guards.DEATH_CASES.items()}
    control('source: Death cases and their (call delta, parent life) are the schema\'s', want, cases, cases == want)
    consts = dict(re.findall(r'const (?:float|int) (\w+) = ([\d./f ]+);', code))
    got = {k: v.strip() for k, v in consts.items()}
    expect = {'CaptureDelta': '1f / 30f', 'SlowTimeScale': '.5f', 'FixedControl': '.0075f', 'BoundaryFrames': '2', 'SettleFrames': '5'}
    control('source: phase constants are the predeclared ones', expect, got, got == expect
            and guards.CAPTURE_DELTA == 1/30 and guards.SLOW_TIME_SCALE == .5 and guards.FIXED_CONTROL == .0075
            and guards.BOUNDARY_FRAMES == 2)
    broad = BROAD.read_text()
    make = re.search(r'static ParticleSystem Make\(string name, Action<ParticleSystem> configure.*?\n    }\n', broad, re.S)
    mine = re.search(r'static ParticleSystem MakeBroad\(string name, Action<ParticleSystem> configure.*?\n    }\n', probe, re.S)
    same_make = bool(make and mine) and squash(make.group(0)).replace('Make(', 'MakeBroad(', 1) == squash(mine.group(0))
    control('source: MakeBroad is the broad probe\'s Make', True, same_make, same_make)
    theirs = re.search(r'ps = Make\("sub_emitters_birth", s =>.*?\}\);', broad, re.S)
    ours = re.search(r'ps = MakeBroad\("sub_emitters_birth", s =>.*?\}\);', probe, re.S)
    same_birth = bool(theirs and ours) and squash(theirs.group(0)).replace('Make(', 'MakeBroad(') == squash(ours.group(0))
    control('source: the Birth system set-up is the broad sub_emitters_birth code', True, same_birth, same_birth)
    loop = 'for (int i = 0; i < 15; i++) { ps.Simulate(0.05f, true, i == 0, false);'
    control('source: the Birth history runs the broad 15 x Simulate(.05, true, i == 0, false)', True,
            loop in squash(probe) and loop in squash(broad), loop in squash(probe) and loop in squash(broad))
    sims = re.findall(r'\.Simulate\(([^)]*)\)', code)
    control('source: only the two planned Simulate calls', ['callDelta, true, false, false', '0.05f, true, i == 0, false'],
            sims, sims == ['callDelta, true, false, false', '0.05f, true, i == 0, false'])
    finals = re.findall(r'finally\s*\{\s*if \((parent|ps) != null\) DestroyImmediate\(', code)
    control('source: every case destroys its systems in finally (before any yield)', ['parent', 'ps'], finals, finals == ['parent', 'ps'])
    forbidden = re.findall(r'GetMeshIndex|meshIndex|GetCustomParticleData|ParticleSystemRenderer|Renderer|Camera|Texture|'
                           r'ReadPixels|EncodeTo|Bake|OrderBy|Sort\(|Linq|UnityEditor|EditorApplication', code)
    control('source: no mesh-index/custom-data/rendering/bake read, no sorting, no Editor API in the probe', [], forbidden, not forbidden)
    yields = [m.start() for m in re.finditer(r'yield return null', code)]
    starts = code.index('IEnumerator Start()')
    control('source: the probe yields only in Start', True, all(y > starts for y in yields) and len(yields) == 3,
            all(y > starts for y in yields) and len(yields) == 3)
    exits = re.findall(r'EditorApplication\.Exit\(', runner)
    control('source: ProbeRunner quits only in Quit() and the no-output path', 2, len(exits), len(exits) == 2)
    quit_body = re.search(r'static void Quit\(int code, string reason\)\s*\{(.*?)\n    \}', runner, re.S)
    order = [m for m in re.findall(r'update -= Tick|playModeStateChanged -= OnState|closed = true|EditorApplication\.Exit', quit_body.group(1))] if quit_body else []
    want_order = ['update -= Tick', 'playModeStateChanged -= OnState', 'closed = true', 'EditorApplication.Exit']
    control('source: Quit removes both handlers and closes the output before Exit', want_order, order, order == want_order)
    state = re.search(r'static void OnState\(PlayModeStateChange state\)\s*\{\s*if \(closed\) return;\s*Event\("state", state\.ToString\(\)\);\s*\}', runner)
    control('source: the play mode state callback only records', 'record-only handler', bool(state), state)
    control('source: the runner does not change Editor settings', [], re.findall(r'EditorSettings', runner), 'EditorSettings' not in runner)
    gate_code = (PROBE/'run.py').read_text()+(PROBE/'guards.py').read_text()
    uses = re.findall(r'import analyze|from analyze|analyze\.\w+\(', gate_code)
    control('source: capture, check and publish never call the analyzer (answers never gate; '
            'run.py only hashes analyze.py as a launch input)', [], uses, not uses)


