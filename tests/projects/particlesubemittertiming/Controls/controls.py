"""Offline controls of the sub-emitter first-age probe's guards, runner protocol, analyzer and
publish gate. No Editor, engine, Host or Unity compiler runs here.

    ~/.cache/compat/with-heavy-job --kind tool python3 Controls/controls.py --out NEW_CACHE_DIR

1. Source guards on the two probe scripts (case constants equal the guards' schema, the Birth
   history is the broad probe's code, systems are destroyed in `finally`, no mesh-index/custom-data/
   rendering read, no sorting, no Editor transition in the probe, the runner quits only from its
   update handler after removing both handlers).
2. Compiles the probe's two real scripts at C# 9 (Unity's language version) against
   FakeUnity.cs with the .NET SDK's Roslyn, and runs them through Driver.cs in seven scenarios.
   The fake answers are plausible, not Unity's: this checks emission and control flow only.
3. The guards must pass the normal captures (positive controls) and refuse every mocked
   negative control: record mutations, run results, inputs, runner events, Editor logs, repeat
   disagreement, launch admission, the compile-graph check and the preflight judgement.
4. The analyzer: the committed PREDICTIONS.json is regenerated byte for byte; synthetic records
   built from one candidate's predictions select exactly that candidate's class; mixed and
   unpredicted records give NONE; the cached Native histories give the receipt's fits. The publish
   path never reads the analyzer (hypothesis answers never gate).

Writes NEW_CACHE_DIR/controls.json with every control's expected and actual result; exit 0 only
when all hold.
"""
