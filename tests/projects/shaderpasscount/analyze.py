#!/usr/bin/env python3
"""Precommitted pass count hypotheses of the shader pass count probe, and their fit to a capture.

    analyze.py predict PREDICTIONS.json         derives every hypothesis's answers from the committed
                                                shader bytes (Assets/Shaders) and the case table
    analyze.py fit VALUES.jsonl --report R.json  which hypotheses a capture fits (never a gate)

The predictions come from the fixture's bytes, not from any captured answer: the SubShaders, their
LODs, tags, pass counts and colour codes are parsed from Assets/Shaders/*.shader, the cases from the
probe's case table (guards.CASES). The initial maximum LODs are taken as measured by the builtinrp
probe's lod.* reference (Shader.maximumLOD -1, Shader.globalMaximumLOD 2147483647); a capture whose
recorded initial values differ is NOT_EVALUABLE, it is never refitted.

Hypotheses for Shader.passCount and Material.passCount (one rule for both):
  FIRST         the declared pass count of the shader's own SubShader 0, whatever is drawn.
  SELECTED      the pass count of the SubShader rendering selects: the first of the shader's
                SubShaders followed by its Fallback chain's whose RenderPipeline tag is absent (the
                built-in pipeline) and whose LOD (none: 0) is at most the shader's limit (its
                maximumLOD, or globalMaximumLOD when that is -1); none: 0.
  RENDERER      Unbound's renderer list at the base of this probe (Shader.passCount from
                ShaderPassInfo; crates/unbound-app/src/shaderlab.rs select_with, the Fallback
                looked up under the same limit): SELECTED's SubShader, but a surface SubShader
                counts its generated forward base and forward add passes (2); none: 0.
  FALLBACK_OWN  the shader's own SubShaders under its limit; when none is in reach, the Fallback
                shader selected under the Fallback's OWN limit (its maximumLOD or the global one),
                and so on; none: 0.
A surface SubShader's pass count is generated by Unity; FIRST, SELECTED and FALLBACK_OWN predict
it relationally as the same capture's passCountInSubshader[i] ({"psc": i}).

Each hypothesis also names the SubShader it implies is drawn (FIRST: own SubShader 0). The colour
an orthographic camera renders identifies the drawn SubShader independently: red/blue are the
SubShader's code (the shaders' pass 0 or surface emission), green counts the passes drawn (one
step of 0.125 per vertex/fragment pass); the background colour means nothing was drawn.

`fit` reports, per readout (passCount before and after the render, the existing and a new
material's passCount), the hypotheses that match every cell, and whether that is ONE, MULTIPLE or
NONE (a valid negative); the same for the drawn SubShader, plus the relations passCount ==
passCountInSubshader[drawn] and passes drawn == passCount. Nothing here is read by run.py or
guards.py: hypothesis answers never gate a capture.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

PROBE = Path(__file__).resolve().parent
sys.path.insert(0, str(PROBE))
import guards  # noqa: E402

SHADERS = PROBE/'Assets/Shaders'
HYPOTHESES = ('FIRST', 'SELECTED', 'RENDERER', 'FALLBACK_OWN')
READOUTS = ('passCount', 'passCount.after', 'mat.passCount', 'mat.passCount.after', 'newMat.passCount')
INITIAL = {'maximumLOD': -1, 'globalMaximumLOD': 2147483647}
INITIAL_SOURCE = 'tests/projects/builtinrp/Reference/values.jsonl lod.maximumLOD, lod.globalMaximumLOD'
GENERATED_FORWARD = 2    # Unbound: a surface SubShader's forward base + forward add pass
STEP = 32                # 0.125 in 8 bits (31.875 rounds to 32)
CODE_TOLERANCE = 8


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def blocks(text, keyword):
    """The bodies of the `keyword { ... }` blocks at the top level of `text` (brace matched)."""
    found, i = [], 0
    while True:
        m = re.compile(r'\b'+keyword+r'\s*\{').search(text, i)
        if not m:
            return found
        depth, j = 1, m.end()
        while depth:
            depth += {'{': 1, '}': -1}.get(text[j], 0)
            j += 1
        found.append(text[m.end():j-1])
        i = j


def parse_shader(path):
    text = re.sub(r'//[^\n]*', '', Path(path).read_text())
    name = re.search(r'Shader\s+"([^"]+)"', text).group(1)
    fallback = re.search(r'Fallback\s+(?:"([^"]+)"|Off)', text)
    subs = []
    for body in blocks(text, 'SubShader'):
        tags = dict(re.findall(r'"(\w+)"\s*=\s*"([^"]*)"', re.search(r'Tags\s*\{([^}]*)\}', body).group(1)))
        lod = re.search(r'^\s*LOD\s+(\d+)', body, re.M)
        surface = '#pragma surface' in body
        if surface:
            r, b = (float(x) for x in re.search(r'o\.Emission = float3\(([\d.]+), 0, ([\d.]+)\)', body).groups())
        else:
            r, b = (float(x) for x in re.search(r'return float4\(([\d.]+), 0\.125, ([\d.]+), 1\)', body).groups())
        subs.append({'id': tags['SubId'], 'lod': int(lod.group(1)) if lod else 0, 'tags': tags,
                     'surface': surface, 'passes': None if surface else len(blocks(body, 'Pass')),
                     'code': [round(r*255), round(b*255)]})
    return {'name': name, 'fallback': fallback.group(1) if fallback and fallback.group(1) else None, 'subs': subs}


def fixture():
    shaders = {}
    for path in sorted(SHADERS.glob('*.shader')):
        s = parse_shader(path)
        s['file'] = str(path.relative_to(PROBE))
        s['sha256'] = sha(path)
        shaders[s['name']] = s
    return shaders


def chain(shaders, name):
    """The SubShaders of `name` followed by its Fallback chain's, each with its owner."""
    out, seen = [], set()
    while name and name not in seen:
        seen.add(name)
        out += [dict(sub, owner=name) for sub in shaders[name]['subs']]
        name = shaders[name]['fallback']
    return out


def runs_here(sub):
    return sub['tags'].get('RenderPipeline', '') == ''


def limit(state, name):
    own = state[name]
    return own if own >= 0 else state['global']


def first_in(subs, lod):
    return next((i for i, s in enumerate(subs) if runs_here(s) and s['lod'] <= lod), None)


def count(sub, index, generated=None):
    if sub['surface']:
        return {'psc': index} if generated is None else generated
    return sub['passes']


def predict_cell(shaders, state, name):
    """{hypothesis: {'passCount': int | {'psc': i}, 'drawn': SubShader id | 'none'}} for one shader."""
    subs = chain(shaders, name)
    own = shaders[name]['subs']
    out = {'FIRST': {'passCount': count(own[0], 0), 'drawn': own[0]['id']}}
    i = first_in(subs, limit(state, name))
    out['SELECTED'] = {'passCount': count(subs[i], i) if i is not None else 0, 'drawn': subs[i]['id'] if i is not None else 'none'}
    out['RENDERER'] = {'passCount': count(subs[i], i, GENERATED_FORWARD) if i is not None else 0,
                       'drawn': out['SELECTED']['drawn']}
    current, offset, picked = name, 0, None
    while current:
        mine = shaders[current]['subs']
        j = first_in(mine, limit(state, current))
        if j is not None:
            picked = (mine[j], offset+j)
            break
        offset += len(mine)
        current = shaders[current]['fallback']
    out['FALLBACK_OWN'] = {'passCount': count(*picked) if picked else 0, 'drawn': picked[0]['id'] if picked else 'none'}
    return out


def predictions():
    shaders = fixture()
    names = dict(zip(guards.KEYS, guards.NAMES))
    state = {n: INITIAL['maximumLOD'] for n in guards.NAMES}
    state['global'] = INITIAL['globalMaximumLOD']
    cases = []
    for case in guards.CASES:
        name = case[0]
        for field, value in zip(guards.SET_FIELDS, case[1:]):
            if value is None:
                continue
            target = 'global' if field == 'global' else names[field]
            state[target] = (INITIAL['globalMaximumLOD'] if field == 'global' else INITIAL['maximumLOD']) \
                if value == guards.RESTORE else value
        cells = {k: predict_cell(shaders, state, names[k]) for k in guards.KEYS}
        cases.append({'case': name, 'limits': {k: state[names[k]] for k in guards.KEYS} | {'global': state['global']},
                      'cells': cells})
    distinct = {}
    for a in HYPOTHESES:
        for b in HYPOTHESES:
            if a < b:
                firm = conditional = 0
                for c in cases:
                    for cell in c['cells'].values():
                        x, y = cell[a]['passCount'], cell[b]['passCount']
                        if x == y:
                            continue
                        if isinstance(x, dict) or isinstance(y, dict):
                            conditional += 1
                        else:
                            firm += 1
                distinct[f'{a}/{b}'] = {'cells_that_differ': firm, 'differ_unless_generated_count_matches': conditional}
    return {
        'scope': 'precommitted from the committed fixture bytes and case table; no captured answer was used',
        'initial': INITIAL, 'initial_source': INITIAL_SOURCE,
        'hypotheses': list(HYPOTHESES), 'readouts': list(READOUTS),
        'shaders': shaders, 'cases': cases, 'distinguishing': distinct,
        'colour': {'step': STEP, 'code_tolerance': CODE_TOLERANCE,
                   'rule': 'red/blue = drawn SubShader code; green/32 = vertex/fragment passes drawn; '
                           'background = nothing drawn'},
    }


def predict(path):
    data = predictions()
    Path(path).write_text(json.dumps(data, indent=1, sort_keys=False)+'\n')
    print('wrote', path, {k: v['cells_that_differ'] for k, v in data['distinguishing'].items()})
    return 0


# ---------------------------------------------------------------- fit

def load(path):
    rows, problems = guards.parse(path)
    return {r['k']: r['v'] for r in rows}


def decode(colour, background, shaders, name):
    """(drawn SubShader id | 'none' | 'unknown', vertex/fragment passes drawn or None)."""
    if not isinstance(colour, dict):
        return 'unknown', None
    rgba = colour['rgba']
    if isinstance(background, dict) and rgba == background['rgba']:
        return 'none', 0
    best = None
    for sub in chain(shaders, name):
        d = max(abs(rgba[0]-sub['code'][0]), abs(rgba[2]-sub['code'][1]))
        if d <= CODE_TOLERANCE and (best is None or d < best[0]):
            best = (d, sub)
    if best is None:
        return 'unknown', None
    sub = best[1]
    return sub['id'], None if sub['surface'] else round(rgba[1]/STEP)


def resolve(predicted, psc):
    if isinstance(predicted, dict):
        i = predicted['psc']
        return psc[i] if isinstance(psc, list) and i < len(psc) else None
    return predicted


def outcome(names):
    return 'ONE' if len(names) == 1 else 'MULTIPLE' if names else 'NONE'


def fit(values_path, report_path):
    data = predictions()
    values = load(values_path)
    shaders = data['shaders']
    names = dict(zip(guards.KEYS, guards.NAMES))
    recorded = {k: values.get(f'setup.{k}.maximumLOD') for k in guards.KEYS}
    recorded['global'] = values.get('setup.globalMaximumLOD')
    evaluable = all(recorded[k] == INITIAL['maximumLOD'] for k in guards.KEYS) and \
        recorded['global'] == INITIAL['globalMaximumLOD']
    report = {'values': str(values_path), 'values_sha256': sha(values_path), 'recorded_initial': recorded,
              'evaluable': evaluable, 'readouts': {}, 'drawn': {}, 'relations': {}, 'cells': []}
    if not evaluable:
        report['outcome'] = 'NOT_EVALUABLE'
        Path(report_path).write_text(json.dumps(report, indent=1)+'\n')
        print('NOT_EVALUABLE: the recorded initial LODs differ from the precommitted ones', recorded)
        return 0
    background = values.get('setup.background')
    mismatches = {r: {h: [] for h in HYPOTHESES} for r in READOUTS}
    drawn_miss = {h: [] for h in HYPOTHESES}
    relation_psc, relation_drawn = [], []
    for c in data['cases']:
        for k in guards.KEYS:
            key = f"case.{c['case']}.{k}"
            psc = values.get(key+'.passCountInSubshader')
            observed = {r: values.get(f'{key}.{r}', 'exception: '+str(values.get(f'{key}.{r}.exception'))) for r in READOUTS}
            drawn, passes = decode(values.get(key+'.color'), background, shaders, names[k])
            cell = {'cell': key, 'observed': observed, 'drawn': drawn, 'passesDrawn': passes, 'predicted': {}}
            for h in HYPOTHESES:
                want = resolve(c['cells'][k][h]['passCount'], psc)
                cell['predicted'][h] = {'passCount': want, 'drawn': c['cells'][k][h]['drawn']}
                for r in READOUTS:
                    if observed[r] != want:
                        mismatches[r][h].append(key)
                if drawn != c['cells'][k][h]['drawn']:
                    drawn_miss[h].append(key)
            ids = [s['id'] for s in chain(shaders, names[k])]
            if drawn in ids and isinstance(psc, list) and ids.index(drawn) < len(psc):
                if observed['passCount'] != psc[ids.index(drawn)]:
                    relation_psc.append(key)
            if passes is not None and observed['passCount'] != passes:
                relation_drawn.append(key)
            report['cells'].append(cell)
    for r in READOUTS:
        fits = [h for h in HYPOTHESES if not mismatches[r][h]]
        report['readouts'][r] = {'fits': fits, 'outcome': outcome(fits),
                                 'mismatches': {h: mismatches[r][h] for h in HYPOTHESES}}
    fits = [h for h in HYPOTHESES if not drawn_miss[h]]
    report['drawn'] = {'fits': fits, 'outcome': outcome(fits), 'mismatches': drawn_miss}
    report['relations'] = {'passCount != passCountInSubshader[drawn]': relation_psc,
                           'passCount != vertex/fragment passes drawn': relation_drawn}
    Path(report_path).write_text(json.dumps(report, indent=1)+'\n')
    for r, v in report['readouts'].items():
        print(f'{r}: {v["outcome"]} {v["fits"]}')
    print(f'drawn SubShader: {report["drawn"]["outcome"]} {report["drawn"]["fits"]}')
    print('relations:', {k: len(v) for k, v in report['relations'].items()})
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest='mode', required=True)
    p = sub.add_parser('predict')
    p.add_argument('out', type=Path)
    f = sub.add_parser('fit')
    f.add_argument('values', type=Path)
    f.add_argument('--report', type=Path, required=True)
    args = parser.parse_args()
    if args.mode == 'predict':
        return predict(args.out)
    return fit(args.values, args.report)


if __name__ == '__main__':
    sys.exit(main())
