def source_guards():
    probe = SCRIPTS[0].read_text()
    runner = SCRIPTS[1].read_text()
    code = re.sub(r'//[^\n]*', '', probe)
    strings = lambda name: re.findall(r'"([^"]*)"', re.search(name+r' = \{([^}]*)\}', code).group(1))  # noqa: E731
    control('source: shader keys and names are the schema\'s', [list(guards.KEYS), list(guards.NAMES)],
            [strings('Keys'), strings('Names')], strings('Keys') == list(guards.KEYS) and strings('Names') == list(guards.NAMES))
    passes = [re.findall(r'"([^"]*)"', row) for row in re.findall(r'new\[\] \{([^}]*)\}', re.search(r'PassNames =(.*?)\};', code, re.S).group(1))]
    want = [list(guards.PASS_NAMES[k]) for k in guards.KEYS]
    control('source: FindPass names per shader are the schema\'s', want, passes, passes == want)
    table = re.search(r'Cases =\s*\{(.*?)\};', code, re.S).group(1)
    cases = []
    for row in re.findall(r'\(("[^"]+"(?:, [^,()]+){4})\)', table):
        name, *rest = [x.strip() for x in row.split(',')]
        cases.append((name.strip('"'), *[None if v == 'null' else guards.RESTORE if v == 'Restore' else int(v) for v in rest]))
    control('source: the case table (order and settings) is the schema\'s', list(guards.CASES), cases, cases == list(guards.CASES))
    const = dict(re.findall(r'const (?:int|string) (\w+) = ([^;]+);', code))
    want = {'SubTag': '"SubId"', 'PassTag': '"PassId"', 'NoTag': '"none"', 'Size': '16', 'SettleFrames': '5',
            'Restore': 'int.MinValue', 'OutputVariable': '"'+guards.OUTPUT_VARIABLE+'"'}
    control('source: probe constants', want, const, const == want and guards.SIZE == 16)
    forbidden = re.findall(r'GetPassName|SetPass|Blit|DrawMeshNow|OrderBy|Sort\(|Reverse\(|UnityEditor|EditorApplication|'
                           r'FindPassTagValue\(\w+, new|GetInstanceID|Process\b|Directory\.|\.realtimeSinceStartup\b|unscaledTime', code)
    control('source: no out-of-range pass access (GetPassName/SetPass/Blit/pass-only FindPassTagValue), no sorting, '
            'no Editor API, no ids/processes in the probe', [], forbidden, not forbidden)
    psc = re.findall(r'GetPassCountInSubshader\(([^)]*)\)', code)
    control('source: per-SubShader counts are read only for 0 <= s < subshaderCount', ['s', 's', 's'], psc, psc == ['s', 's', 's'])
    diag = re.search(r'void Diagnostic\(string what\)\s*\{(.*?)\n    \}', code, re.S)
    outside = code.replace(diag.group(0), '') if diag else code
    leaks = re.findall(r'Time\.\w+|graphicsDeviceName|graphicsDeviceVersion', outside)
    control('source: real time, frames and device names only in Diagnostic (never in the record)', [], leaks, diag and not leaks)
    start = re.search(r'IEnumerator Start\(\)\s*\{(.*?)\n    \}', code, re.S).group(1)
    order = re.findall(r'Block\("cleanup", Cleanup\)|Value\("complete"|File\.Move|yield return null|finishedCode = code', start)
    want = ['Block("cleanup", Cleanup)', 'Value("complete"', 'File.Move', 'yield return null', 'finishedCode = code']
    control('source: cleanup, marker and closed output before the only yields, then the finished code', want, order, order == want)
    yields = re.findall(r'yield return', code)
    control('source: the probe yields only in Start', 1, len(yields), len(yields) == 1)
    exits = re.findall(r'EditorApplication\.Exit\(', runner)
    control('source: ProbeRunner quits only in Quit() and the no-output path', 2, len(exits), len(exits) == 2)
    quit_body = re.search(r'static void Quit\(int code, string reason\)\s*\{(.*?)\n    \}', runner, re.S)
    order = re.findall(r'update -= Tick|playModeStateChanged -= OnState|closed = true|EditorApplication\.Exit', quit_body.group(1)) if quit_body else []
    want_order = ['update -= Tick', 'playModeStateChanged -= OnState', 'closed = true', 'EditorApplication.Exit']
    control('source: Quit removes both handlers and closes the output before Exit', want_order, order, order == want_order)
    state = re.search(r'static void OnState\(PlayModeStateChange state\)\s*\{\s*if \(closed\) return;\s*Event\("state", state\.ToString\(\)\);\s*\}', runner)
    control('source: the play mode state callback only records', 'record-only handler', bool(state), state)
    record = re.search(r'public static void Record\(\)\s*\{(.*?)\n    \}', runner, re.S).group(1)
    settings = re.findall(r'EditorSettings\.\w+ = \w+;', runner)
    in_record = re.findall(r'EditorSettings\.asyncShaderCompilation = false;\s*EditorSceneManager\.OpenScene', record)
    control('source: the runner changes only asyncShaderCompilation, in Record before opening the scene (as the '
            'shader keyword capture)', ['EditorSettings.asyncShaderCompilation = false;'], settings,
            settings == ['EditorSettings.asyncShaderCompilation = false;'] and len(in_record) == 1)
    keywords = (REPO/'tests/projects/shaderkeywords/Assets/Editor/ProbeRunner.cs').read_text()
    control('source: the shader keyword runner sets the same setting the same way', True,
            'EditorSettings.asyncShaderCompilation = false;' in keywords, 'EditorSettings.asyncShaderCompilation = false;' in keywords)
    gate_code = (PROBE/'run.py').read_text()+(PROBE/'guards.py').read_text()
    uses = re.findall(r'import analyze|from analyze|analyze\.\w+\(', gate_code)
    control('source: capture, check and publish never call the analyzer (answers never gate; '
            'run.py only hashes analyze.py as a launch input)', [], uses, not uses)
    for path in sorted((PROBE/'Assets/Shaders').glob('*.shader')):
        text = path.read_text()
        vf = text.count('#pragma fragment frag')
        states = text.count('ZTest Always ZWrite Off Cull Off')
        subs = len(analyze.blocks(re.sub(r'//[^\n]*', '', text), 'SubShader'))
        surface = text.count('#pragma surface')
        control(f'source: {path.name}: every vertex/fragment SubShader draws regardless of depth; first pass '
                'replaces, later passes add one green step', [subs - surface, vf - text.count('Blend Off')],
                [states, text.count('Blend One One')], states == subs - surface and text.count('Blend One One') == vf - text.count('Blend Off'))
    copies = {}
    for part in ('Packages', 'ProjectSettings'):
        mine, theirs = preflight.files(PROBE/part), preflight.files(REPO/'tests/projects/shaderkeywords'/part)
        copies[part] = mine == theirs
    for rel in ('Assets/Scenes/Probe.unity', 'Assets/Scenes/Probe.unity.meta', 'Assets/Editor/ProbeRunner.cs.meta'):
        copies[rel] = sha(PROBE/rel) == sha(REPO/'tests/projects/shaderkeywords'/rel)
    control('source: Packages, ProjectSettings, scene and runner .meta are byte copies of the shader keyword fixture',
            True, copies, all(copies.values()))


# ---------------------------------------------------------------- 2. compile and drive

def dotnet():
    root = Path.home()/'.dotnet'
    csc = sorted((root/'sdk').glob('10.*/Roslyn/bincore/csc.dll'))[-1]
    refs = sorted((root/'packs/Microsoft.NETCore.App.Ref').glob('10.*/ref/net10.0'))[-1]
    version = refs.parent.parent.name
    return root/'dotnet', csc, sorted(refs.glob('*.dll')), version


def compile_all(out):
    exe, csc, refs, version = dotnet()
    build = out/'build'
    build.mkdir()
    record = {'dotnet': str(exe), 'csc': str(csc), 'csc_sha256': sha(csc), 'framework': version, 'steps': []}
    common = ['/nologo', '/nostdlib+', '/noconfig', *[f'/r:{r}' for r in refs]]
    steps = [
        ('FakeUnity', ['/target:library', '/nowarn:0618,0660,0661', str(HERE/'FakeUnity.cs')], []),
        ('Probe', ['/target:library', '/langversion:9.0', '/nowarn:0618,0649,0169', *map(str, SCRIPTS)], ['FakeUnity']),
        ('Driver', ['/target:exe', str(HERE/'Driver.cs')], ['FakeUnity']),
    ]
    for name, args, deps in steps:
        rsp = build/f'{name}.rsp'
        rsp.write_text('\n'.join('"'+a+'"' for a in [*common, *[f'/r:{build/d}.dll' for d in deps],
                                                    f'/out:{build/name}.dll', *args])+'\n')
        process = subprocess.run([str(exe), str(csc), '@'+str(rsp)], capture_output=True, text=True)
        (build/f'{name}.log').write_text(process.stdout+process.stderr)
        record['steps'].append({'name': name, 'exit': process.returncode, 'output': (process.stdout+process.stderr).strip()})
        if process.returncode:
            control(f'compile {name} at C# {"9" if name == "Probe" else "default"}', 0, process.stdout+process.stderr, False)
            return None, record
    (build/'Driver.runtimeconfig.json').write_text(json.dumps({'runtimeOptions': {
        'tfm': 'net10.0', 'framework': {'name': 'Microsoft.NETCore.App', 'version': version},
        'rollForward': 'LatestPatch'}}))
    control('compile the probe scripts at C# 9 against the fakes', 0, 0, True)
    return build, record


def drive(build, out):
    exe = dotnet()[0]
    runs = {}
    for scenario in SCENARIOS:
        target = out/'scenarios'/scenario
        process = subprocess.run([str(exe), str(build/'Driver.dll'), scenario.replace('-repeat', ''),
                                  str(build/'Probe.dll'), str(target)], capture_output=True, text=True)
        (out/'scenarios'/f'{scenario}.log').write_text(process.stdout+process.stderr)
        driver = json.loads((target/'driver.json').read_text()) if (target/'driver.json').exists() else None
        runs[scenario] = {'dir': target, 'process': process.returncode, 'driver': driver}
    return runs


