def write_rows(path, rows):
    path.write_text(''.join(json.dumps(r, separators=(',', ':'))+'\n' for r in rows))


def record_controls(normal, out):
    base = guards.parse(normal)[0]
    work = out/'record-controls'
    work.mkdir()

    def index(key):
        return next(i for i, r in enumerate(base) if r['k'] == key)

    def mutated(name, change, expect):
        rows = copy.deepcopy(base)
        text = change(rows)
        path = work/(re.sub(r'\W+', '-', name)+'.jsonl')
        if isinstance(text, str):
            path.write_text(text)
        else:
            write_rows(path, rows)
        problems = guards.record_problems(path, RELEASE, DEVICE)
        control('record refused: '+name, expect, problems[:4], any(expect in p for p in problems))

    def setv(key, value):
        def change(rows):
            rows[index(key)]['v'] = value
        return change
    full = normal.read_text()
    mutated('completion-only', lambda rows: '{"k":"complete","v":true}\n', 'missing context.unityVersion')
    mutated('truncated by lines', lambda rows: ''.join(full.splitlines(True)[:len(base)*2//3]), 'completion marker is not the last line')
    mutated('truncated mid-line', lambda rows: full[:len(full)//2], 'truncated')
    mutated('omitted case', lambda rows: rows.__setitem__(slice(None), [r for r in rows if not r['k'].startswith('case.shader175.')]), 'missing case.shader175')
    mutated('omitted shader readback', lambda rows: rows.__setitem__(slice(None), [r for r in rows if not r['k'].startswith('case.global100.surface.')]), 'missing case.global100.surface')
    mutated('omitted read', lambda rows: rows.pop(index('case.shader25.lod.passCount')), 'missing case.shader25.lod.passCount')
    mutated('omitted declarations block log', lambda rows: rows.pop(index('decl.tagged.log')), 'missing decl.tagged.log')
    mutated('omitted cleanup block', lambda rows: rows.pop(index('cleanup.log')), 'missing cleanup.log')
    mutated('duplicate key', lambda rows: rows.insert(index('case.default.log'), dict(rows[index('case.default.log')-1])), 'duplicate key')
    mutated('reordered readbacks', lambda rows: rows.insert(index('case.shader350.lod.maximumLOD'), rows.pop(index('case.shader350.lod.passCount'))), 'unexpected record')
    mutated('wrong type (passCount as text)', setv('case.default.lod.passCount', '3'), 'case.default.lod.passCount: wrong type')
    mutated('colour channel out of range', setv('case.default.lod.color', {'rgba': [32, 300, 0, 255], 'uniform': True}), 'case.default.lod.color: wrong type')
    mutated('colour without uniformity', setv('case.default.lod.color', {'rgba': [32, 96, 0, 255]}), 'case.default.lod.color: wrong type')
    mutated('FindPass list of another length', setv('case.default.tagged.mat.findPass', [0, 1]), 'case.default.tagged.mat.findPass: wrong type')
    mutated('authored setting changed', setv('case.shader350.set', {'lod': 351}), 'case.shader350.set: not the authored setting')
    mutated('authored restore changed', setv('case.globalRestored.set', {'lod': 'initial'}), 'case.globalRestored.set: not the authored setting')
    mutated('fatal record', lambda rows: rows.insert(len(rows)-1, {'k': 'fatal', 'v': 'boom'}), 'fatal')
    mutated('two markers', lambda rows: rows.insert(5, {'k': 'complete', 'v': True}), '2 completion markers')
    mutated('marker not last', lambda rows: rows.append(rows.pop(-2)), 'completion marker is not the last line')
    mutated('extra key', lambda rows: rows.insert(index('case.default.log'), {'k': 'case.default.extra', 'v': 1}), 'unexpected record case.default.extra')
    mutated('probe fault', lambda rows: rows.insert(index('case.shader100.log'), {'k': 'case.shader100.exception', 'v': 'NullReferenceException: x'}), 'probe fault in block case.shader100')
    mutated('fixture shader not found', setv('setup.surface.found', False), 'probe shader surface was not found')
    mutated('set-up step failed', lambda rows: rows.insert(index('setup.actualRenderingPath'), {'k': 'setup.step[camera].exception', 'v': 'Exception: x'}), 'could not set up')
    mutated('wrong release', setv('context.unityVersion', '6000.0.70f1'), 'context.unityVersion')
    mutated('wrong device', setv('context.graphicsDeviceType', 'Null'), 'context.graphicsDeviceType')
    mutated('not batchmode', setv('context.isBatchMode', False), 'context.isBatchMode')
    mutated('a scriptable render pipeline', setv('context.renderPipeline', 'UniversalRP'), 'context.renderPipeline')
    mutated('unscoped error', setv('capture.unscopedLogs', ['Error: boom']), 'unexpected errors outside the probe cases')
    mutated('not a k/v record', lambda rows: full.replace('{"k":"case.default.log"', '{"key":"case.default.log"', 1), 'not a {"k","v"} record')
    # Answers are data: values that contradict every hypothesis still pass the schema guard.
    rows = copy.deepcopy(base)
    for r in rows:
        if r['k'].endswith('passCount') or r['k'].endswith('passCount.after'):
            r['v'] = 77
        if r['k'].endswith('.isSupported'):
            r['v'] = not r['v']
        if r['k'].endswith('.color'):
            r['v'] = {'rgba': [1, 2, 3, 4], 'uniform': False}
        if r['k'].endswith('.mat.subTag'):
            r['v'] = None
    rows = [{'k': r['k']+'.exception', 'v': 'ArgumentException: x'} if r['k'] == 'case.shader25.surface.passCount' else r
            for r in rows]
    for r in rows:
        if r['k'] == 'case.shader25.log':
            r['v'] = ['Error: an expected API error']
    path = work/'answers-are-data.jsonl'
    write_rows(path, rows)
    problems = guards.record_problems(path, RELEASE, DEVICE)
    control('record accepted: any pass count/support/colour/tag answer, a per-read exception and a scoped error log '
            '(answers never gate)', [], problems, not problems)


