def control(name, expect, actual, passed):
    results.append({'control': name, 'expect': expect, 'actual': actual, 'passed': bool(passed)})


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def squash(text):
    return re.sub(r'\s+', ' ', text).strip()


