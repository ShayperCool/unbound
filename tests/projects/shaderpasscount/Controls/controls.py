#!/usr/bin/env python3
"""Offline controls of the shader pass count probe's guards, runner protocol, analyzer, preflight
judgement and publish gate. No Editor, engine, Host or Unity compiler runs here.

    ~/.cache/compat/with-heavy-job --kind tool python3 Controls/controls.py --out NEW_CACHE_DIR

1. Source guards on the probe scripts and shaders (case table, shader keys and pass names equal the
   guards' schema; no out-of-range pass access, no sorting, no Editor API in the probe; real time,
   frames and device names only in the diagnostics; the probe yields only after writing; the
   runner changes the shader compilation setting only in Record and quits only from its update
   handler after removing both handlers).
2. Compiles the probe's two real scripts at C# 9 (Unity's language version) against
   FakeUnity.cs with the .NET SDK's Roslyn, and runs them through Driver.cs in seven scenarios.
   The fake answers are plausible, not Unity's: this checks emission and control flow only.
3. The guards must pass the normal captures (positive controls) and refuse every mocked
   negative control: record mutations, run results, inputs, runner events, Editor logs, repeat
   disagreement, launch admission, the compile-graph check, the preflight judgement and its
   identity proof.
4. The analyzer: the committed PREDICTIONS.json is regenerated byte for byte; synthetic records
   built from one hypothesis's predictions select exactly that hypothesis (or the hypotheses that
   predict the same answers); mixed and unpredicted records give NONE; a record with other initial
   LODs is NOT_EVALUABLE. The publish path never reads the analyzer (answers never gate).

Writes NEW_CACHE_DIR/controls.json with every control's expected and actual result; exit 0 only
when all hold.
"""
