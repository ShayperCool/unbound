def obj(name, points, quads, statements, material=None):
    """`statements[i]` is written before face i (a smoothing or material line, or None)."""
    lines = ['# Generated by tests/projects/modelimport/make_smoothing_models.py']
    if material:
        lines.append(f'mtllib {material}')
    lines.append(f'o {name}')
    lines += [f'v {x!r} {y!r} {z!r}' for x, y, z in points]
    for quad, before in zip(quads, statements):
        lines += before or []
        lines.append('f ' + ' '.join(str(i + 1) for i in reversed(quad)))
    return '\n'.join(lines) + '\n'


