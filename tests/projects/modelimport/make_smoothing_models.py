def main():
    OUT.mkdir(parents=True, exist_ok=True)
    files = {}
    points, quads = grid(4, 1)
    faces = len(quads)
    masks = [1, 1, 2, 2, 1, 3, 2, 4, 4, 0, 4, 8, 0x80000000, 0x80000001, 8, 8]
    assert len(masks) == faces
    files['GroupsAscii.fbx'] = fbx_mesh('GroupsAscii', points, quads, {'mapping': 'ByPolygon', 'values': masks})
    # The reference type is not read for smoothing; the index array is ignored.
    files['GroupsIndexed.fbx'] = fbx_mesh('GroupsIndexed', points, quads, {
        'mapping': 'ByPolygon', 'reference': 'IndexToDirect', 'values': masks,
        'index': list(reversed(range(faces)))})
    # Version 101 layers are flags: every non-zero mask becomes 1.
    files['GroupsFlags.fbx'] = fbx_mesh('GroupsFlags', points, quads, {
        'version': 101, 'mapping': 'ByPolygon', 'values': [2, 4, 0, 8] * 4})
    corners = [m for q, m in zip(quads, masks) for _ in q]
    files['GroupsCorners.fbx'] = fbx_mesh('GroupsCorners', points, quads, {
        'mapping': 'ByPolygonVertex', 'values': [c if i % 3 else c | 16 for i, c in enumerate(corners)]})
    files['GroupsPoints.fbx'] = fbx_mesh('GroupsPoints', points, quads, {
        'mapping': 'ByVertice', 'values': [1 << (i % 3) for i in range(len(points))]})
    files['GroupsAllSame.fbx'] = fbx_mesh('GroupsAllSame', points, quads, {'mapping': 'AllSame', 'values': [6]})
    files['GroupsAllZero.fbx'] = fbx_mesh('GroupsAllZero', points, quads, {'mapping': 'AllSame', 'values': [0]})
    files['GroupsShort.fbx'] = fbx_mesh('GroupsShort', points, quads, {'mapping': 'ByPolygon', 'values': masks[:10]})
    files['GroupsLegacy.fbx'] = legacy_fbx('GroupsLegacy', points, quads, masks)
    # A mapping token the importer does not know, and per-point values of the wrong count.
    files['GroupsByVertex.fbx'] = fbx_mesh('GroupsByVertex', points, quads, {
        'mapping': 'ByVertex', 'values': [1 << (i % 3) for i in range(len(points))]})
    files['GroupsPointsShort.fbx'] = fbx_mesh('GroupsPointsShort', points, quads, {
        'mapping': 'ByVertice', 'values': [1 << (i % 3) for i in range(len(points) - 3)]})
    # Edge smoothing on a 6 x 6 grid.
    points6, quads6 = grid(6, 2)
    edges6 = edges_of(quads6)
    for pattern in ('L', 'T', 'Cross', 'Ring', 'Sparse', 'Dense'):
        sharp = sharp_edges(6, pattern, seed=7)
        files[f'Edges{pattern}.fbx'] = fbx_mesh(f'Edges{pattern}', points6, quads6, {
            'mapping': 'ByEdge', 'values': edge_values(edges6, sharp)}, [e for e, _ in edges6])
    # The same dense pattern with the edge list reversed and given from the other face's corner.
    sharp = sharp_edges(6, 'Dense', seed=7)
    corner_of = {}
    corner = 0
    for quad in quads6:
        for k, a in enumerate(quad):
            b = quad[(k + 1) % 4]
            corner_of.setdefault((min(a, b), max(a, b)), []).append(corner + k)
        corner += 4
    reordered = [(corner_of[key][-1], key) for _, key in reversed(edges6)]
    files['EdgesReordered.fbx'] = fbx_mesh('EdgesReordered', points6, quads6, {
        'mapping': 'ByEdge', 'values': edge_values(reordered, sharp)}, [e for e, _ in reordered])
    files['EdgesIndexed.fbx'] = fbx_mesh('EdgesIndexed', points6, quads6, {
        'mapping': 'ByEdge', 'reference': 'IndexToDirect', 'values': edge_values(edges6, sharp_edges(6, 'T')),
        'index': list(range(len(edges6)))}, [e for e, _ in edges6])
    # Edge arrays shorter and longer than the edge list.
    t_values = edge_values(edges6, sharp_edges(6, 'T'))
    files['EdgesShort.fbx'] = fbx_mesh('EdgesShort', points6, quads6, {
        'mapping': 'ByEdge', 'values': t_values[:60]}, [e for e, _ in edges6])
    files['EdgesLong.fbx'] = fbx_mesh('EdgesLong', points6, quads6, {
        'mapping': 'ByEdge', 'values': t_values + [0] * 8}, [e for e, _ in edges6])
    # Take spans: (properties, key times).
    keys = [0.25, 0.5, 0.75]
    for name, props, single in [('TakeStop', [('LocalStop', 1.0)], False),
                                ('TakeStart', [('LocalStart', 0.5)], False),
                                ('TakeNone', [], False),
                                ('TakeReversed', [('LocalStart', 1.0), ('LocalStop', 0.5)], False),
                                ('TakeEmpty', [('LocalStart', 0.5), ('LocalStop', 0.5)], False),
                                ('TakeReference', [('ReferenceStart', 0.0), ('ReferenceStop', 2.0)], False),
                                ('TakeSingleKey', [], True)]:
        files[name + '.fbx'] = take(name, props, keys, single)
    # Takes without curves, with and without a time span.
    files['TakeNoCurves.fbx'] = take('TakeNoCurves', [('LocalStop', 1.0)], keys, curves=False)
    files['TakeNoCurvesNoTime.fbx'] = take('TakeNoCurvesNoTime', [], keys, curves=False)
    # A span ending between keys, and two layers keyed at different times without a span.
    files['TakeStopBetween.fbx'] = take('TakeStopBetween', [('LocalStop', 0.6)], keys)
    files['TakeTwoLayers.fbx'] = take('TakeTwoLayers', [], keys, second_layer=[1.0, 1.25, 1.5])
    # OBJ smoothing statements.
    rng = random.Random(3)
    groups = [[f's {rng.choice([1, 2, 3, 4])}'] for _ in quads]
    groups[5] = ['s off']
    groups[9] = ['s 0']
    files['ObjGroups.obj'] = obj('ObjGroups', points, quads, groups)
    on = [None] * faces
    on[0], on[6], on[11] = ['s on'], ['s 2'], ['s on']
    files['ObjOn.obj'] = obj('ObjOn', points, quads, on)
    files['ObjOnOnly.obj'] = obj('ObjOnOnly', points, quads, [['s on']] + [None] * (faces - 1))
    # Faces without a material under the legacy material import, in a named group.
    files['ObjLegacy.obj'] = obj('ObjLegacy', points, quads, [['g left arm', 's 1']] + [None] * (faces - 1))
    odd = [None] * faces
    odd[0], odd[4], odd[8], odd[12] = ['s -1'], ['s 33'], ['s 1.5'], ['s 6']
    files['ObjOdd.obj'] = obj('ObjOdd', points, quads, odd)
    mixed = [[f's {1 + (i * 7) % 3}', f'usemtl {"Red" if (i // 3) % 2 else "Blue"}'] for i in range(faces)]
    files['ObjMaterials.obj'] = obj('ObjMaterials', points, quads, mixed, 'Smoothing.mtl')
    keyed = [['usemtl ' + ['LambertIllum', 'PhongKeys', 'FilterOnly', 'DissolveAndFilter'][i % 4]]
             for i in range(faces)]
    files['ObjKeys.obj'] = obj('ObjKeys', points, quads, keyed, 'Smoothing.mtl')
    (OUT/'Smoothing.mtl').write_text(MTL)
    default = 'fileFormatVersion: 2\nguid: {}\n{}DefaultImporter:\n  externalObjects: {{}}\n  userData: \n  assetBundleName: \n  assetBundleVariant: \n'
    (OUT/'Smoothing.mtl.meta').write_text(default.format(guid('Smoothing.mtl'), ''))
    OUT.with_name('Smoothing.meta').write_text(default.format(guid('Smoothing'), 'folderAsset: yes\n'))
    for name, text in files.items():
        path = OUT/name
        path.write_text(text)
        write_meta(path, animated=name.startswith('Take'), legacy=name == 'ObjLegacy.obj')
    print('wrote', len(files), 'models to', OUT)


if __name__ == '__main__':
    main()
