def fbx_mesh(name, points, quads, layer=None, edges=None, extra_objects='', extra_connections=''):
    vertices = [c for p in points for c in p]
    indices = [i if k < len(q) - 1 else -i - 1 for q in quads for k, i in enumerate(q)]
    parts = [array('Vertices', vertices, 2), array('PolygonVertexIndex', indices, 2)]
    if edges is not None:
        parts.append(array('Edges', edges, 2))
    parts.append('\t\tGeometryVersion: 124')
    elements = []
    if layer is not None:
        parts.append(smoothing_layer(layer))
        elements.append('LayerElementSmoothing')
    parts.append('\t\tLayer: 0 {\n\t\t\tVersion: 100\n' + ''.join(
        f'\t\t\tLayerElement:  {{\n\t\t\t\tType: "{e}"\n\t\t\t\tTypedIndex: 0\n\t\t\t}}\n'
        for e in elements) + '\t\t}')
    kinds = {'Model': 1, 'Geometry': 1}
    for kind in ('AnimationStack', 'AnimationLayer', 'AnimationCurveNode', 'AnimationCurve'):
        if f'\t{kind}: ' in extra_objects:
            kinds[kind] = extra_objects.count(f'\t{kind}: ')
    definitions = '\n'.join(f'\tObjectType: "{k}" {{\n\t\tCount: {v}\n\t}}' for k, v in kinds.items())
    return HEADER + f'''Definitions:  {{
\tVersion: 100
\tCount: {sum(kinds.values())}
{definitions}
}}
Objects:  {{
\tGeometry: 1000, "Geometry::{name}", "Mesh" {{
{chr(10).join(parts)}
\t}}
\tModel: 2000, "Model::{name}", "Mesh" {{
\t\tVersion: 232
\t\tShading: T
\t\tCulling: "CullingOff"
\t}}
{extra_objects}}}
Connections:  {{
\tC: "OO",2000,0
\tC: "OO",1000,2000
{extra_connections}}}
'''


def sharp_edges(n, pattern, seed=0):
    """Undirected control-point pairs of the sharp edges of an n x n grid."""
    p = lambda x, z: z * (n + 1) + x
    h = lambda x, z: (p(x, z), p(x + 1, z))    # along x at row z
    v = lambda x, z: (p(x, z), p(x, z + 1))    # along z at column x
    if pattern == 'L':
        # Two chains meeting at a corner, and a separate sharp edge.
        return {h(1, 2), h(2, 2), v(3, 2), v(3, 3), v(1, 4)}
    if pattern == 'T':
        return {h(1, 3), h(2, 3), h(3, 3), h(4, 3), v(3, 3), v(3, 4)}
    if pattern == 'Cross':
        return {h(2, 3), h(3, 3), v(3, 2), v(3, 3), h(1, 1), v(2, 1)}
    if pattern == 'Ring':
        # A closed loop with a tail and a separate sharp chain touching it at a corner.
        return {h(1, 1), h(2, 1), h(1, 3), h(2, 3), v(1, 1), v(1, 2), v(3, 1), v(3, 2),
                v(3, 3), v(3, 4), h(4, 1)}
    rng = random.Random(seed)
    every = {h(x, z) for x in range(n) for z in range(1, n)} | {v(x, z) for x in range(1, n) for z in range(n)}
    share = {'Sparse': 0.2, 'Dense': 0.55}[pattern]
    return {e for e in sorted(every) if rng.random() < share}


def edge_values(edges, sharp):
    return [0 if key in sharp or (key[1], key[0]) in sharp else 1 for _, key in edges]


def take(name, props, keys, single_key=False, curves=True, second_layer=None):
    """A cube animated along x (or, without `curves`, not at all), with an animation stack of the
    given time properties; `second_layer` keys a second layer's y curve at those times."""
    points = [(x, y, z) for z in (-0.5, 0.5) for y in (-0.5, 0.5) for x in (-0.5, 0.5)]
    quads = [(0, 2, 3, 1), (4, 5, 7, 6), (0, 1, 5, 4), (2, 6, 7, 3), (0, 4, 6, 2), (1, 3, 7, 5)]
    times = [int(round(t * KTIME)) for t in keys[:1 if single_key else None]]
    values = [float(i % 2) for i in range(len(times))]
    stack_props = ''.join(f'\t\t\tP: "{k}", "KTime", "Time", "",{int(round(v * KTIME))}\n' for k, v in props)
    objects = f'''\tAnimationStack: 3000, "AnimStack::{name}", "" {{
\t\tProperties70:  {{
{stack_props}\t\t}}
\t}}
\tAnimationLayer: 3001, "AnimLayer::BaseLayer", "" {{
\t}}
'''
    curve_objects = f'''\tAnimationCurveNode: 3002, "AnimCurveNode::T", "" {{
\t\tProperties70:  {{
\t\t\tP: "d|X", "Number", "", "A",0
\t\t\tP: "d|Y", "Number", "", "A",0
\t\t\tP: "d|Z", "Number", "", "A",0
\t\t}}
\t}}
\tAnimationCurve: 3003, "AnimCurve::", "" {{
\t\tDefault: 0
\t\tKeyVer: 4009
{array('KeyTime', times, 2)}
{array('KeyValueFloat', values, 2)}
{array('KeyAttrFlags', [24836], 2)}
{array('KeyAttrDataFloat', [0, 0, 218434821, 0], 2)}
{array('KeyAttrRefCount', [len(times)], 2)}
\t}}
'''
    connections = '''\tC: "OO",3001,3000
\tC: "OO",3002,3001
\tC: "OP",3002,2000, "Lcl Translation"
\tC: "OP",3003,3002, "d|X"
'''
    if curves:
        objects += curve_objects
    else:
        connections = connections.splitlines(keepends=True)[0]
    if second_layer:
        times2 = [int(round(t * KTIME)) for t in second_layer]
        objects += f'''\tAnimationLayer: 3101, "AnimLayer::Second", "" {{
\t}}
\tAnimationCurveNode: 3102, "AnimCurveNode::T", "" {{
\t\tProperties70:  {{
\t\t\tP: "d|X", "Number", "", "A",0
\t\t\tP: "d|Y", "Number", "", "A",0
\t\t\tP: "d|Z", "Number", "", "A",0
\t\t}}
\t}}
\tAnimationCurve: 3103, "AnimCurve::", "" {{
\t\tDefault: 0
\t\tKeyVer: 4009
{array('KeyTime', times2, 2)}
{array('KeyValueFloat', [float(i % 2) for i in range(len(times2))], 2)}
{array('KeyAttrFlags', [24836], 2)}
{array('KeyAttrDataFloat', [0, 0, 218434821, 0], 2)}
{array('KeyAttrRefCount', [len(times2)], 2)}
\t}}
'''
        connections += '\tC: "OO",3101,3000\n\tC: "OO",3102,3101\n\tC: "OP",3102,2000, "Lcl Translation"\n\tC: "OP",3103,3102, "d|Y"\n'
    return fbx_mesh(name, points, quads, extra_objects=objects, extra_connections=connections)


