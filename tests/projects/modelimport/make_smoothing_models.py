#!/usr/bin/env python3
"""Writes Assets/Resources/Smoothing: small authored models for smoothing and take ranges.

FBX (ASCII 7.4, one 6.1 file) grids with smoothing layers in each encoding (polygon groups,
indexed and boolean layers, per corner, per control point, all same, short arrays, edge
smoothing with L, T, cross and scattered sharp edges, edges in another order), takes whose
time span is incomplete, and OBJ files with smoothing statements (numbered, `on`, `off`,
negative, wide and fractional groups, interleaved groups with two materials). Every model gets a
`.meta` with calculated normals and mesh optimization off, so the vertex and triangle order is
the importer's own.

    python3 tests/projects/modelimport/make_smoothing_models.py
"""
import hashlib
import math
import random
from pathlib import Path

PROBE = Path(__file__).resolve().parent
OUT = PROBE/'Assets/Resources/Smoothing'
# The settings of every geometry fixture; takes import animation with a generic rig.
META_TEMPLATE = PROBE/'Assets/Resources/Slots/DeclaredCalculate.fbx.meta'
KTIME = 46186158000  # FBX time units per second


def guid(name):
    return hashlib.md5(('unbound-smoothing-' + name).encode()).hexdigest()


def write_meta(path, animated=False, legacy=False):
    text = META_TEMPLATE.read_text()
    lines = text.splitlines()
    assert lines[1].startswith('guid: ')
    lines[1] = 'guid: ' + guid(path.name)
    text = '\n'.join(lines) + '\n'
    if animated:
        for old, new in [('  importAnimation: 0\n', '  importAnimation: 1\n'),
                         ('  animationType: 0\n', '  animationType: 2\n')]:
            assert old in text
            text = text.replace(old, new)
    if legacy:
        assert '    materialImportMode: 2\n' in text
        text = text.replace('    materialImportMode: 2\n', '    materialImportMode: 1\n')
    path.with_name(path.name + '.meta').write_text(text)


def grid(n, seed):
    """An n x n grid of quads over a bumpy height field (no two neighbours coplanar)."""
    rng = random.Random(seed)
    points = [(x - n / 2, 0.35 * math.sin(1.3 * x + 0.7 * z) + 0.2 * rng.random(), z - n / 2)
              for z in range(n + 1) for x in range(n + 1)]
    quads = [(z * (n + 1) + x, (z + 1) * (n + 1) + x, (z + 1) * (n + 1) + x + 1, z * (n + 1) + x + 1)
             for z in range(n) for x in range(n)]
    return points, quads


def edges_of(quads):
    """Each undirected edge once, as the polygon-vertex index of its first occurrence."""
    seen, edges, corner = {}, [], 0
    for quad in quads:
        for k, a in enumerate(quad):
            b = quad[(k + 1) % len(quad)]
            key = (min(a, b), max(a, b))
            if key not in seen:
                seen[key] = len(edges)
                edges.append((corner + k, key))
        corner += len(quad)
    return edges


def number(v):
    return repr(float(v)) if isinstance(v, float) else str(v)


def array(name, values, tabs):
    t = '\t' * tabs
    return f'{t}{name}: *{len(values)} {{\n{t}\ta: {",".join(number(v) for v in values)}\n{t}}}'


def smoothing_layer(layer, tabs=2):
    t = '\t' * tabs
    body = [f'{t}\tVersion: {layer.get("version", 102)}', f'{t}\tName: ""',
            f'{t}\tMappingInformationType: "{layer["mapping"]}"',
            f'{t}\tReferenceInformationType: "{layer.get("reference", "Direct")}"',
            array('Smoothing', layer['values'], tabs + 1)]
    if 'index' in layer:
        body.append(array('SmoothingIndex', layer['index'], tabs + 1))
    return f'{t}LayerElementSmoothing: 0 {{\n' + '\n'.join(body) + f'\n{t}}}'


