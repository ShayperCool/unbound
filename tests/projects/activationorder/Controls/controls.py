def write_rows(path, rows):
    path.write_text(''.join(json.dumps(r, separators=(',', ':'))+'\n' for r in rows))


def record_controls(normal, out):
    base = guards.parse(normal)[0]
    work = out/'record-controls'
    work.mkdir()

    def index(key):
        return next(i for i, r in enumerate(base) if r['k'] == key)

    def mutated(name, change, expect):
        rows = copy.deepcopy(base)
        text = change(rows)
        path = work/(re.sub(r'\W+', '-', name)+'.jsonl')
        if isinstance(text, str):
            path.write_text(text)
        else:
            write_rows(path, rows)
        problems = guards.record_problems(path, RELEASE, DEVICE)
        control('record refused: '+name, expect, problems[:4], any(expect in p for p in problems))

    def setv(key, value):
        def change(rows):
            rows[index(key)]['v'] = value
        return change
    full = normal.read_text()
    entry = base[index('op.plainOff.calls')]['v'][0]
    mutated('completion-only', lambda rows: '{"k":"complete","v":true}\n', 'missing context.unityVersion')
    mutated('truncated by lines', lambda rows: ''.join(full.splitlines(True)[:len(base)*2//3]), 'completion marker is not the last line')
    mutated('truncated mid-line', lambda rows: full[:len(full)//2], 'truncated')
    mutated('omitted operation', lambda rows: rows.__setitem__(slice(None), [r for r in rows if not r['k'].startswith('op.spanOn.')]), 'missing op.spanOn')
    mutated('omitted first-wake control', lambda rows: rows.__setitem__(slice(None), [r for r in rows if not r['k'].startswith('wake.')]), 'missing wake.plainOn')
    mutated('omitted node state', lambda rows: rows.pop(index('op.nativeOff.after.G')), 'missing op.nativeOff.after.G')
    mutated('omitted calls list', lambda rows: rows.pop(index('op.plainOn.calls')), 'missing op.plainOn.calls')
    mutated('omitted NativeArray step position (reordered)', lambda rows: rows.insert(index('op.nativeOn.relativeFrame'), rows.pop(index('op.nativeOn.returned'))), 'unexpected record')
    mutated('omitted block log', lambda rows: rows.pop(index('settle.log')), 'missing settle.log')
    mutated('omitted stray list', lambda rows: rows.pop(index('capture.strayCalls')), 'missing capture.strayCalls')
    mutated('duplicate key', lambda rows: rows.insert(index('op.plainOff.log'), dict(rows[index('op.plainOff.log')-1])), 'duplicate key')
    mutated('calls entry without its state', setv('op.plainOff.calls', [{'n': entry['n'], 'cb': entry['cb']}]), 'op.plainOff.calls: wrong type')
    mutated('calls entry with an unknown label', setv('op.plainOff.calls', [dict(entry, n='X')]), 'op.plainOff.calls: wrong type')
    mutated('calls entry with an unknown callback', setv('op.plainOff.calls', [dict(entry, cb='OnDestroy')]), 'op.plainOff.calls: wrong type')
    mutated('calls entry with reordered fields', setv('op.plainOff.calls', [{'cb': entry['cb'], 'n': entry['n'], 'self': entry['self']}]), 'op.plainOff.calls: wrong type')
    state = base[index('op.plainOff.before.P')]['v']
    mutated('state without counts', setv('op.plainOff.before.P', {k: v for k, v in state.items() if k != 'counts'}), 'op.plainOff.before.P: wrong type')
