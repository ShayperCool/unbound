def hypothesis_record(base_rows, data, pick, path):
    """The fake record with every operation's calls replaced by pick(key)'s predicted list."""
    rows = copy.deepcopy(base_rows)
    for r in rows:
        if r['k'].endswith('.calls') and r['k'].rsplit('.', 1)[0] in data['operations']:
            key = r['k'].rsplit('.', 1)[0]
            h = pick(key)
            want = data['operations'][key]['hypotheses'][h] if h else [{'n': 'U', 'cb': 'OnDisable'}]
            r['v'] = [dict(e, self=[True, True, True, True]) for e in want]
    write_rows(path, rows)
    return path


