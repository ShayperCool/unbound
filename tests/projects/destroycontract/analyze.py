#!/usr/bin/env python3
"""Precommitted Destroy-request mechanisms and callback delivery brackets, and their fit.

    analyze.py predict PREDICTIONS.json          writes the predictions (committed; regenerated by the controls)
    analyze.py fit VALUES.jsonl --report R.json   which precommitted hypotheses fit a capture

Nothing in run.py or guards.py reads this module: answers never gate a capture.

State mechanisms (what a Destroy request does before it returns). Evaluated per case on the
reads made just before and just after the request, and on the callbacks of each read subject
between its `request` and `returned` events (the global raw order). A case whose before-read is
not the authored set-up state is NOT_EVALUABLE for that case, never refitted.

  GameObject Destroy (every case but comp.update; target and, for tree.parent, its child):
    FLAG_ONLY          public state unchanged, no callback before returning
    CALLBACK_ONLY      public state unchanged, OnDisable before returning if the behaviour was
                       active and enabled
    CALLBACK_INACTIVE  as CALLBACK_ONLY, but isActiveAndEnabled false (active/enabled flags and
                       Find unchanged)
    DEACTIVATE         as SetActive(false) on the target: target activeSelf false, every read
                       subject activeInHierarchy/isActiveAndEnabled false, enabled unchanged, Find
                       none, still alive; OnDisable before returning if it was active and enabled
    LEAVE_HIERARCHY    activeSelf unchanged, activeInHierarchy/isActiveAndEnabled false, enabled
                       unchanged, Find none, alive; OnDisable as DEACTIVATE
    DISABLE_BEHAVIOURS active state and Find unchanged, enabled/isActiveAndEnabled false, alive;
                       OnDisable as DEACTIVATE
    NULL_PENDING       Unity-null at once (state reads throw, Find none); OnDisable as DEACTIVATE,
                       OnDestroy later
    IMMEDIATE          Unity-null at once; OnDisable as DEACTIVATE and OnDestroy (if Awake ran)
                       before returning
  Component Destroy (comp.update; the GameObject's alive/activeSelf/activeInHierarchy/Find
  predicted unchanged by all):
    C_FLAG_ONLY        unchanged, no callback
    C_CALLBACK_ONLY    unchanged, OnDisable
    C_DISABLE          enabled/isActiveAndEnabled false, still listed by GetComponent; OnDisable
    C_INACTIVE_FLAG    enabled unchanged, isActiveAndEnabled false, GetComponent same; OnDisable
    C_DETACH_PENDING   component alive, enabled unchanged, isActiveAndEnabled false, GetComponent
                       none; OnDisable
    C_NULL_PENDING     component Unity-null (reads throw), GetComponent none; OnDisable
    C_IMMEDIATE        as C_NULL_PENDING with OnDisable and OnDestroy before returning

Delivery brackets (where a deferred OnDestroy, or an OnDisable not delivered before returning,
is called). The bracket is the position of the callback between the probe's leaf markers, with
the frame relative to the request's frame (d). Predicted from the request's position in the
CAPTURED loop listing (loop.leaves):
    SAME_LEAF          in the request's own leaf (Update/LateUpdate requests), or for a request
                       made between leaves in the next leaf, same frame (next frame on wrap)
    NEXT_DELAYED       in the first leaf named ScriptRunDelayed* after the request
    FRAME_DRAINS       in the first PostLateUpdate.PlayerSendFrameStarted or
                       PostLateUpdate.PlayerSendFrameComplete after the request (the current
                       Unbound queue drains)
    NEXT_FRAME_START   in the first leaf of the next frame (d not constrained)
    OUTSIDE_LOOP       after the last leaf (between frames; d not constrained)
A hypothesis fits a callback kind if it predicts every deferred callback of it (overall and per
request point). Outcomes: ONE, MULTIPLE (cannot distinguish within this fixture) or NONE (a valid
negative); a callback before the request returned is BEFORE_RETURN and one never seen by the final
step NOT_DELIVERED_BY_FINAL_STEP (data, not a fit). The bracket says which leaf's marker pair the
call happened between, not which internal node made it. The reentrant case (DESCRIPTIVE_CASES) is
reported per case only and never enters an intersection.

Descriptive (no hypothesis): per case the subject's callback counters at every snapshot point
from the request until its OnDestroy (subsequent Update/LateUpdate/end-of-frame delivery), and the
reentrant subject's raw event sequence.
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys

PROBE = Path(__file__).resolve().parent
REPO = PROBE.parents[2]
sys.path.insert(0, str(PROBE))
from guards import CASES, FINAL_STEP, LABELS, POINTS, POINT_POSITION, SUBJECTS, case_reads, parse  # noqa: E402

# The default loop as recorded by a Unity 6000.0.71f1 Editor capture (the input probe's
# canonical); used only to tabulate predictions before capture. The fit uses the captured loop.
REFERENCE_LOOP = REPO/'tests/projects/input/Reference/unity-6000.0.71f1.jsonl'
GO_MECHANISMS = ('FLAG_ONLY', 'CALLBACK_ONLY', 'CALLBACK_INACTIVE', 'DEACTIVATE', 'LEAVE_HIERARCHY', 'DISABLE_BEHAVIOURS',
                 'NULL_PENDING', 'IMMEDIATE')
COMPONENT_MECHANISMS = ('C_FLAG_ONLY', 'C_CALLBACK_ONLY', 'C_DISABLE', 'C_INACTIVE_FLAG', 'C_DETACH_PENDING',
                        'C_NULL_PENDING', 'C_IMMEDIATE')
BRACKETS = ('SAME_LEAF', 'NEXT_DELAYED', 'FRAME_DRAINS', 'NEXT_FRAME_START', 'OUTSIDE_LOOP')
FIELDS = ('alive', 'activeSelf', 'activeInHierarchy', 'enabled', 'isActiveAndEnabled', 'find')
COMPONENT_FIELDS = ('alive', 'activeSelf', 'activeInHierarchy', 'find', 'comp', 'enabled', 'isActiveAndEnabled',
                    'getComponent')
EXCEPTION = '!exception'    # any exception type name
# Cases fitted and reported per case but kept out of the mechanism/delivery intersections: the
# reentrant case changes the callback itself, so it is descriptive only.
DESCRIPTIVE_CASES = ('reenter',)


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def reference_leaves():
    leaves = []
    for line in REFERENCE_LOOP.read_text().splitlines():
        row = json.loads(line)
        if row.get('k') == 'playerLoop':
            leaves += [row['phase']+'.'+s for s in row['systems'].split(',')]
    return leaves


# ---------------------------------------------------------------- authored states

def authored_before():
    """The public state each subject has before its case, from the authored set-up alone."""
    setup = {label: (parent, kind) for label, parent, kind in SUBJECTS}
    states = {}
    for label, parent, kind in SUBJECTS:
        self_active = kind != 'inactive'
        in_hierarchy = self_active and (parent is None or setup[parent][1] != 'inactive')
        enabled = kind != 'disabled'
        states[label] = {'alive': True, 'activeSelf': self_active, 'activeInHierarchy': in_hierarchy,
                         'enabled': enabled, 'isActiveAndEnabled': in_hierarchy and enabled,
                         'find': 'same' if in_hierarchy else 'none', 'comp': True, 'getComponent': 'same',
                         # Every subject is created active and gets its observer while active (the
                         # probe deactivates or disables only afterwards), so Awake ran for all.
                         'awake': True}
    return states


def go_prediction(mechanism, before, role):
    """(after fields, callbacks before returning) of one read subject under a GameObject mechanism."""
    b = before
    disable = ['OnDisable'] if b['isActiveAndEnabled'] else []
    same = {k: b[k] for k in FIELDS}
    if mechanism == 'FLAG_ONLY':
        return same, []
    if mechanism == 'CALLBACK_ONLY':
        return same, disable
    if mechanism == 'CALLBACK_INACTIVE':
        return dict(same, isActiveAndEnabled=False), disable
    if mechanism == 'DEACTIVATE':
        return dict(same, activeSelf=False if role == 'target' else b['activeSelf'], activeInHierarchy=False,
                    isActiveAndEnabled=False, find='none'), disable
    if mechanism == 'LEAVE_HIERARCHY':
        return dict(same, activeInHierarchy=False, isActiveAndEnabled=False, find='none'), disable
    if mechanism == 'DISABLE_BEHAVIOURS':
        return dict(same, enabled=False, isActiveAndEnabled=False), disable
    dead = {'alive': False, 'activeSelf': EXCEPTION, 'activeInHierarchy': EXCEPTION, 'enabled': EXCEPTION,
            'isActiveAndEnabled': EXCEPTION, 'find': 'none'}
    if mechanism == 'NULL_PENDING':
        return dead, disable
    if mechanism == 'IMMEDIATE':
        return dead, disable+(['OnDestroy'] if b['awake'] else [])
    raise ValueError(mechanism)


def component_prediction(mechanism, before):
    b = before
    same = {k: b[k] for k in COMPONENT_FIELDS}
    disable = ['OnDisable'] if b['isActiveAndEnabled'] else []
    if mechanism == 'C_FLAG_ONLY':
        return same, []
    if mechanism == 'C_CALLBACK_ONLY':
        return same, disable
    if mechanism == 'C_DISABLE':
        return dict(same, enabled=False, isActiveAndEnabled=False), disable
    if mechanism == 'C_INACTIVE_FLAG':
        return dict(same, isActiveAndEnabled=False), disable
    if mechanism == 'C_DETACH_PENDING':
        return dict(same, isActiveAndEnabled=False, getComponent='none'), disable
    dead = dict(same, comp=False, enabled=EXCEPTION, isActiveAndEnabled=EXCEPTION, getComponent='none')
    if mechanism == 'C_NULL_PENDING':
        return dead, disable
    if mechanism == 'C_IMMEDIATE':
        return dead, disable+['OnDestroy']
    raise ValueError(mechanism)


# ---------------------------------------------------------------- delivery brackets

def parse_position(p, leaves):
    """(kind, index) of a bracket position; ('boot', -1) before the first marker."""
    if p == 'boot':
        return 'boot', -1
    kind, _, leaf = p.partition(':')
    return kind, leaves.index(leaf) if leaf in leaves else None


def first_after(leaves, start, include_start, match):
    """(d, index) of the first leaf (in frame order) at or after start that matches."""
    n = len(leaves)
    for offset in range(0 if include_start else 1, 2*n+1):
        i = start+offset
        if match(leaves[i % n]):
            return i//n, i % n
    return None


def bracket(hypothesis, request_position, leaves):
    """The predicted (position, frame offset or None) of a deferred callback."""
    kind, index = parse_position(request_position, leaves)
    if index is None or index < 0:
        return None
    if hypothesis == 'SAME_LEAF':
        if kind == 'in':
            return 'in:'+leaves[index], 0
        d, i = first_after(leaves, index, False, lambda leaf: True)
        return 'in:'+leaves[i], d
    if hypothesis == 'NEXT_DELAYED':
        found = first_after(leaves, index, False, lambda leaf: leaf.split('.')[-1].startswith('ScriptRunDelayed'))
        return ('in:'+leaves[found[1]], found[0]) if found else None
    if hypothesis == 'FRAME_DRAINS':
        found = first_after(leaves, index, False, lambda leaf: leaf in ('PostLateUpdate.PlayerSendFrameStarted',
                                                                        'PostLateUpdate.PlayerSendFrameComplete'))
        return ('in:'+leaves[found[1]], found[0]) if found else None
    if hypothesis == 'NEXT_FRAME_START':
        return 'in:'+leaves[0], None
    if hypothesis == 'OUTSIDE_LOOP':
        return 'after:'+leaves[-1], None
    raise ValueError(hypothesis)


# ---------------------------------------------------------------- predictions

def predictions():
    leaves = reference_leaves()
    before = authored_before()
    cases = []
    for name, step, point, subject, target in CASES:
        reads = case_reads(subject)
        entry = {'case': name, 'step': step, 'point': point, 'subject': subject, 'target': target, 'reads': reads,
                 'request_position': POINT_POSITION[point],
                 'before': {r: {k: before[r][k] for k in (COMPONENT_FIELDS if target == 'component' else FIELDS)}
                            for r in reads}}
        if target == 'component':
            entry['mechanisms'] = {m: {subject: dict(zip(('after', 'during'), component_prediction(m, before[subject])))}
                                   for m in COMPONENT_MECHANISMS}
        else:
            entry['mechanisms'] = {m: {r: dict(zip(('after', 'during'), go_prediction(m, before[r], 'target' if r == subject else 'child')))
                                       for r in reads} for m in GO_MECHANISMS}
        entry['brackets'] = {h: bracket(h, POINT_POSITION[point], leaves) for h in BRACKETS}
        cases.append(entry)
    return {'note': 'precommitted from the committed case/subject tables and authored set-up; brackets tabulated '
                    'with the reference loop listing below, refitted only against the CAPTURED loop listing',
            'final_step': FINAL_STEP, 'points': list(POINTS),
            'reference_loop': {'path': str(REFERENCE_LOOP.relative_to(REPO)), 'sha256': sha(REFERENCE_LOOP),
                               'leaves': leaves},
            'go_mechanisms': list(GO_MECHANISMS), 'component_mechanisms': list(COMPONENT_MECHANISMS),
            'brackets': list(BRACKETS), 'cases': cases,
            'outcomes': ['ONE', 'MULTIPLE', 'NONE', 'NOT_EVALUABLE']}


def predict(path):
    Path(path).write_text(json.dumps(predictions(), indent=1)+'\n')
    print('wrote', path)


# ---------------------------------------------------------------- fit

def matches(predicted, actual):
    if predicted == EXCEPTION:
        return isinstance(actual, str) and actual.startswith('!')
    return predicted == actual


def window(order, subject, label):
    """The callbacks of `label` between `subject:request` and `subject:returned` in the global order."""
    try:
        start = order.index(subject+':request')
        end = order.index(subject+':returned', start)
    except ValueError:
        return None
    return [t.rpartition(':')[2] for t in order[start+1:end]
            if t.rpartition(':')[0] == label and t.rpartition(':')[2] in ('OnDisable', 'OnDestroy')]


def outcome(fits):
    return 'NONE' if not fits else 'ONE' if len(fits) == 1 else 'MULTIPLE'


def indexed_traces(values):
    """Per subject, its trace events with their index in the global raw order (None when the
    order and the traces disagree; the guards refuse such a record)."""
    order = values.get('order')
    traces = {label: values.get('trace.'+label) for label in LABELS}
    if not isinstance(order, list) or not all(isinstance(t, list) for t in traces.values()):
        return None
    cursor = {label: 0 for label in LABELS}
    indexed = {label: [] for label in LABELS}
    for g, token in enumerate(order):
        label, _, what = str(token).rpartition(':')
        if label not in cursor or cursor[label] >= len(traces[label]) or traces[label][cursor[label]].get('e') != what:
            return None
        indexed[label].append((g, traces[label][cursor[label]]))
        cursor[label] += 1
    if any(cursor[label] != len(traces[label]) for label in LABELS):
        return None
    return indexed


def fit(path, report):
    records, problems = parse(path)
    values = {r['k']: r['v'] for r in records}
    leaves = values.get('loop.leaves') or []
    order = values.get('order') or []
    indexed = indexed_traces(values)
    result = {'capture': str(path), 'capture_sha256': sha(path), 'parse_problems': problems,
              'order_consistent': indexed is not None,
              'loop_equals_reference': leaves == reference_leaves(), 'cases': {}}
    go_fits, comp_fits = set(GO_MECHANISMS), set(COMPONENT_MECHANISMS)
    go_evaluated = comp_evaluated = 0
    delivery = {kind: {'all': {h: True for h in BRACKETS}, 'count': 0,
                       'points': {p: {'fits': {h: True for h in BRACKETS}, 'count': 0} for p in POINTS}}
                for kind in ('OnDisable', 'OnDestroy')}
    authored = authored_before()
    for name, step, point, subject, target in CASES:
        reads = case_reads(subject)
        fields = COMPONENT_FIELDS if target == 'component' else FIELDS
        case = {'reads': {}, 'mechanisms': {}, 'delivery': {}, 'in_intersection': name not in DESCRIPTIVE_CASES}
        evaluable = indexed is not None
        for r in reads:
            b = values.get(f'case.{name}.before.{r}')
            a = values.get(f'case.{name}.after.{r}')
            during = window(order, subject, r)
            case['reads'][r] = {'before': b, 'after': a, 'during': during}
            if not isinstance(b, dict) or not isinstance(a, dict) or during is None \
                    or any(b.get(k) != authored[r][k] for k in fields):
                evaluable = False
        mechanisms = COMPONENT_MECHANISMS if target == 'component' else GO_MECHANISMS
        if evaluable:
            for m in mechanisms:
                ok = True
                for r in reads:
                    if target == 'component':
                        after, during = component_prediction(m, authored[r])
                    else:
                        after, during = go_prediction(m, authored[r], 'target' if r == subject else 'child')
                    got = case['reads'][r]
                    if not all(matches(after[k], got['after'].get(k)) for k in after) or got['during'] != during:
                        ok = False
                case['mechanisms'][m] = ok
            fitting = sorted(m for m, ok in case['mechanisms'].items() if ok)
            case['mechanism_fits'] = fitting
            case['mechanism_outcome'] = outcome(fitting)
            if case['in_intersection']:
                if target == 'component':
                    comp_fits &= set(fitting)
                    comp_evaluated += 1
                else:
                    go_fits &= set(fitting)
                    go_evaluated += 1
        else:
            case['mechanism_outcome'] = 'NOT_EVALUABLE'
        request = None
        if indexed is not None:
            request = next(((g, e) for g, e in indexed[subject] if e.get('e') == 'request'), None)
        for r in reads:
            during = case['reads'][r]['during'] or []
            for kind in ('OnDisable', 'OnDestroy'):
                key = f'{r}.{kind}'
                if request is None:
                    case['delivery'][key] = {'outcome': 'NOT_EVALUABLE'}
                    continue
                if kind in during:
                    case['delivery'][key] = {'outcome': 'BEFORE_RETURN'}
                    continue
                hit = next((e for g, e in indexed[r] if g > request[0] and e.get('e') == kind), None)
                if hit is None:
                    case['delivery'][key] = {'outcome': 'NOT_DELIVERED_BY_FINAL_STEP'}
                    continue
                d = hit['f']-request[1]['f']
                fits = {}
                for h in BRACKETS:
                    want = bracket(h, request[1]['p'], leaves) if leaves else None
                    fits[h] = want is not None and hit['p'] == want[0] and (want[1] is None or want[1] == d)
                case['delivery'][key] = {'outcome': 'DEFERRED', 'actual': {'p': hit['p'], 'd': d, 's': hit['s']},
                                         'fits': fits, 'fitting': sorted(h for h, ok in fits.items() if ok)}
                if case['in_intersection']:
                    entry = delivery[kind]
                    entry['count'] += 1
                    entry['points'][point]['count'] += 1
                    for h in BRACKETS:
                        entry['all'][h] = entry['all'][h] and fits[h]
                        entry['points'][point]['fits'][h] = entry['points'][point]['fits'][h] and fits[h]
        case['after_request'] = subsequent(values, name, subject, step, point, values.get('trace.'+subject) or [])
        result['cases'][name] = case
    result['go_mechanisms'] = {'evaluated_cases': go_evaluated, 'fits': sorted(go_fits) if go_evaluated else [],
                               'outcome': outcome(sorted(go_fits)) if go_evaluated else 'NOT_EVALUABLE'}
    result['component_mechanisms'] = {'evaluated_cases': comp_evaluated, 'fits': sorted(comp_fits) if comp_evaluated else [],
                                      'outcome': outcome(sorted(comp_fits)) if comp_evaluated else 'NOT_EVALUABLE'}
    result['delivery'] = {}
    for kind, entry in delivery.items():
        fits = sorted(h for h, ok in entry['all'].items() if ok) if entry['count'] else []
        result['delivery'][kind] = {
            'deferred_callbacks': entry['count'], 'fits': fits,
            'outcome': outcome(fits) if entry['count'] else 'NOT_EVALUABLE',
            'points': {p: {'deferred_callbacks': v['count'],
                           'fits': sorted(h for h, ok in v['fits'].items() if ok) if v['count'] else [],
                           'outcome': outcome(sorted(h for h, ok in v['fits'].items() if ok)) if v['count'] else 'NOT_EVALUABLE'}
                       for p, v in entry['points'].items()}}
    result['reenter'] = {'trace': values.get('trace.reenter'), 'note': 'descriptive only; never fitted'}
    Path(report).write_text(json.dumps(result, indent=1)+'\n')
    print(json.dumps({k: result[k] for k in ('order_consistent', 'go_mechanisms', 'component_mechanisms', 'delivery')}, indent=1))
    return result


def subsequent(values, name, subject, step, point, trace):
    """The subject's callback counters at every snapshot point from its request until its
    OnDestroy (or the end), relative to the before-read of the case (descriptive)."""
    before = values.get(f'case.{name}.before.{subject}') or {}
    base = before.get('cb', {})
    destroyed = next((e['s'] for e in trace if e.get('e') == 'OnDestroy'), FINAL_STEP)
    rows = []
    for s in range(step, min(destroyed+1, FINAL_STEP)+1):
        for p in POINTS:
            if s == step and POINTS.index(p) <= POINTS.index(point):
                continue
            snap = values.get(f'snap.{s}.{p}.{subject}')
            if snap is None:
                continue
            cb = snap.get('cb', {})
            rows.append({'s': s, 'point': p, 'alive': snap.get('alive'),
                         'delta': {k: cb.get(k, 0)-base.get(k, 0) for k in ('update', 'late', 'eof', 'disable', 'destroy')}})
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest='what', required=True)
    p = sub.add_parser('predict')
    p.add_argument('out', type=Path)
    f = sub.add_parser('fit')
    f.add_argument('values', type=Path)
    f.add_argument('--report', type=Path, required=True)
    args = parser.parse_args()
    if args.what == 'predict':
        predict(args.out)
    else:
        fit(args.values, args.report)
    return 0


if __name__ == '__main__':
    sys.exit(main())
