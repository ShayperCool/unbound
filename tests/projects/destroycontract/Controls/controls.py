def preflight_identity_controls(out):
    """The identity proof on a mocked capture copy and launch receipt of the source fixture."""
    work = out/'preflight-identity'
    own = {'Assets/Scripts/DestroyContractProbe.cs.meta'}

    def mock_copy(name, change=None):
        root = work/name
        copy_dir = root/'projects/native1'
        launch = root/'native1'
        for part in ('Packages', 'ProjectSettings'):
            shutil.copytree(PROBE/part, copy_dir/part)
        for p in sorted((PROBE/'Assets').rglob('*')):
            rel = str(p.relative_to(PROBE))
            if p.is_file() and p.suffix != '.cs' and rel not in own:
                (copy_dir/rel).parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(p, copy_dir/rel)
        for rel in ('Assets/Scripts/ShaderPassCountProbe.cs', 'Assets/Editor/ProbeRunner.cs', 'Assets/Shaders/PassLod.shader'):
            (copy_dir/rel).parent.mkdir(parents=True, exist_ok=True)
            (copy_dir/rel).write_text('// mock\n')
        (copy_dir/'Library/ScriptAssemblies').mkdir(parents=True)
        for a in ('Assembly-CSharp', 'Assembly-CSharp-Editor'):
            (copy_dir/f'Library/ScriptAssemblies/{a}.dll').write_bytes(b'mock')
        launch.mkdir(parents=True)
        files = {}
        for part, label in (('Packages', 'packages'), ('ProjectSettings', 'settings'), ('Assets', 'assets')):
            for rel, digest in preflight.files(copy_dir/part).items():
                files[f'{label}/{rel}'] = {'path': str(copy_dir/part/rel), 'sha256': digest}
        files['runner'] = {'path': '/x/run.py', 'sha256': '2'*64}
        (launch/'prelaunch-inputs.json').write_text(json.dumps({'selected_release': RELEASE, 'files': files}))
        (launch/'editor-run.json').write_text(json.dumps({
            'exit_code': 0, 'forced_exit': None, 'kind': 'editor-gpu', 'renderer': 'NVIDIA GeForce RTX 4060/PCIe/SSE2',
            'command': ['vglrun', '-d', 'egl', '/x/Editor/Unity', '-batchmode', '-projectPath', str(copy_dir),
                        '-executeMethod', 'ProbeRunner.Record']}))
        settings = copy_dir/'ProjectSettings/EditorSettings.asset'
        settings.write_text(settings.read_text().replace('m_AsyncShaderCompilation: 1', 'm_AsyncShaderCompilation: 0'))
        if change:
            change(copy_dir, launch)
        written, proof = {}, {}
        return preflight.identity(copy_dir, launch, RELEASE, written, proof), proof

    problems, proof = mock_copy('good')
    control('preflight identity: a launched copy of these Packages/ProjectSettings/non-script assets whose only later '
            'change is the source runner\'s asyncShaderCompilation passes', [], problems,
            not problems and proof['copy_settings_changed_after_compile'] == {
                'ProjectSettings/EditorSettings.asset': [('-  m_AsyncShaderCompilation: 1', '+  m_AsyncShaderCompilation: 0')]})

    def edit_json(path, change):
        data = json.loads(path.read_text())
        change(data)
        path.write_text(json.dumps(data))

    def other_setting(c, _):
        p = c/'ProjectSettings/EditorSettings.asset'
        p.write_text(p.read_text().replace('m_SerializationMode: 2', 'm_SerializationMode: 1'))

    def launched_other_package(_, launch):
        edit_json(launch/'prelaunch-inputs.json', lambda d: d['files']['packages/manifest.json'].update(sha256='1'*64))

    def launched_other_scene(_, launch):
        edit_json(launch/'prelaunch-inputs.json', lambda d: d['files']['assets/Scenes/Probe.unity'].update(sha256='1'*64))

    def asmdef(c, _):
        (c/'Assets/Scripts/Probe.asmdef').write_text('{}')

    def plugin(c, _):
        (c/'Assets/Plugins').mkdir()
        (c/'Assets/Plugins/x.dll').write_bytes(b'x')

    def extra_script(c, _):
        (c/'Assets/Scripts/Other.cs').write_text('//\n')

    def forced(_, launch):
        edit_json(launch/'editor-run.json', lambda d: d.update(forced_exit='shutdown-guard'))

    def other_copy(_, launch):
        edit_json(launch/'editor-run.json', lambda d: d['command'].__setitem__(6, '/elsewhere'))

    def not_compiled(c, _):
        (c/'Library/ScriptAssemblies/Assembly-CSharp.dll').unlink()

    def package_changed(c, _):
        (c/'Packages/manifest.json').write_text('{}')

    def other_release(_, launch):
        edit_json(launch/'prelaunch-inputs.json', lambda d: d.update(selected_release='6000.0.70f1'))
    for name, change, expect in (
            ('another settings change in the copy', other_setting, 'changed beyond the runner'),
            ('launched with another package manifest', launched_other_package, 'not this fixture'),
            ('launched with another scene', launched_other_scene, 'non-script assets not launched with these bytes'),
            ('an assembly definition in the copy', asmdef, 'compile inputs under Assets'),
            ('a plugin in the copy', plugin, 'compile inputs under Assets'),
            ('a second Assembly-CSharp script', extra_script, 'not exactly one Assembly-CSharp script'),
            ('a forced launch', forced, 'not a strict exit-0'),
            ('the launch of another copy', other_copy, 'not a strict exit-0'),
            ('not compiled by the Editor', not_compiled, 'did not compile Assembly-CSharp'),
            ('a package changed in the copy', package_changed, 'Packages/manifest.json differs'),
            ('another release', other_release, 'selected 6000.0.70f1')):
        problems, _ = mock_copy(re.sub(r'\W+', '-', name), change)
        control('preflight identity refused: '+name, expect, problems[:3], any(expect in p for p in problems))


