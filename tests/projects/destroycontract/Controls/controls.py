def write_rows(path, rows):
    path.write_text(''.join(json.dumps(r, separators=(',', ':'))+'\n' for r in rows))


def record_controls(normal, out):
    base = guards.parse(normal)[0]
    work = out/'record-controls'
    work.mkdir()

    def index(key):
        return next(i for i, r in enumerate(base) if r['k'] == key)

    def mutated(name, change, expect):
        rows = copy.deepcopy(base)
        text = change(rows)
        path = work/(re.sub(r'\W+', '-', name)+'.jsonl')
        if isinstance(text, str):
            path.write_text(text)
        else:
            write_rows(path, rows)
        problems = guards.record_problems(path, RELEASE, DEVICE)
        control('record refused: '+name, expect, problems[:4], any(expect in p for p in problems))

    def setv(key, value):
        def change(rows):
            rows[index(key)]['v'] = value
        return change

    def trace_edit(label, edit):
        def change(rows):
            edit(rows[index('trace.'+label)]['v'])
        return change
    full = normal.read_text()
    mutated('completion-only', lambda rows: '{"k":"complete","v":true}\n', 'missing context.unityVersion')
    mutated('truncated by lines', lambda rows: ''.join(full.splitlines(True)[:len(base)*2//3]), 'completion marker is not the last line')
    mutated('truncated mid-line', lambda rows: full[:len(full)//2], 'truncated')
    mutated('omitted snapshot point', lambda rows: rows.__setitem__(slice(None), [r for r in rows if not r['k'].startswith('snap.7.teofc.')]), 'missing snap.7.teofc.keep')
    mutated('omitted case read', lambda rows: rows.pop(index('case.tree.parent.after.tree.child')), 'missing case.tree.parent.after.tree.child')
    mutated('omitted trace', lambda rows: rows.pop(index('trace.go.teofc')), 'missing trace.go.teofc')
    mutated('omitted order', lambda rows: rows.pop(index('order')), 'missing order')
    mutated('duplicate key', lambda rows: rows.insert(index('order'), dict(rows[index('order')-1])), 'duplicate key')
    mutated('reordered points', lambda rows: rows.insert(index('snap.3.update.keep'), rows.pop(index('snap.3.late.keep'))), 'unexpected record')
    mutated('extra key', lambda rows: rows.insert(index('order'), {'k': 'trace.extra', 'v': []}), 'unexpected record trace.extra')
    mutated('state without a field', setv('snap.2.update.keep', {k: v for k, v in base[index('snap.2.update.keep')]['v'].items() if k != 'find'}), 'snap.2.update.keep: wrong type')
    mutated('state fields reordered', setv('snap.2.update.keep', dict(reversed(list(base[index('snap.2.update.keep')]['v'].items())))), 'snap.2.update.keep: wrong type')
    mutated('callback count as text', setv('snap.2.update.keep', dict(base[index('snap.2.update.keep')]['v'], cb=dict(base[index('snap.2.update.keep')]['v']['cb'], update='2'))), 'snap.2.update.keep: wrong type')
    mutated('unknown event name', trace_edit('keep', lambda t: t.append({'e': 'OnSomething', 's': 3, 'f': 4, 'p': 'boot'})), 'trace.keep: wrong type')
    mutated('step outside the run', trace_edit('keep', lambda t: t.append({'e': 'OnDestroy', 's': guards.FINAL_STEP+1, 'f': 30, 'p': 'boot'})), 'trace.keep: wrong type')
    mutated('authored subject table changed', setv('setup.subjects', [list(s) for s in guards.SUBJECTS[::-1]]), 'setup.subjects: not the authored')
