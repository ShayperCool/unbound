def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def body(code, signature):
    """The body of a C# member whose declaration matches `signature` (brace matched)."""
    m = re.search(signature, code)
    if not m:
        return None
    start = code.index('{', m.end()-1 if code[m.end()-1] == '{' else m.end())
    depth = 0
    for i in range(start, len(code)):
        depth += {'{': 1, '}': -1}.get(code[i], 0)
        if depth == 0:
            return code[start+1:i]
    return None


