#!/usr/bin/env python3
"""The predeclared short-segment blend cases of the line probe and their C# table.

    blend_cases.py            writes Assets/Scripts/BlendCases.cs from CASES
    blend_cases.py --check    fails when Assets/Scripts/BlendCases.cs is not up to date
    blend_cases.py --list     prints every case with its points and shortness

Every case is a world-space LineRenderer made by the probe's NewLine (width 0.4 from the
constant width curve times the multiplier, View alignment, the orthographic main camera, white
gradient, no corner or cap vertices, Stretch): only the points differ from the other cases.
Its full baked mesh is recorded as `blend.<name>`.

A case is a start point and segments, each a length given as a ratio of the width W and a
direction in degrees in the XY plane. The shortness of a segment of length L,
clamp(2W/L - 1, 0, 1), is listed for reference: it is how the existing cases were described,
not an assumption of the probe. The families:

- L: one corner, equal lengths (90 and 30 degree turns);
- asym: one corner, unequal lengths;
- Z: three or four segments (a staircase, a same-sense U, a short segment between two long ones,
  a collinear run into a turn);
- rev: the same points as an asym or Z case in reverse order.
"""
import argparse
import math
from pathlib import Path
import struct
import sys

WIDTH = 0.4
START = (-0.5, -0.4)
PROBE = Path(__file__).resolve().parent
OUTPUT = PROBE/'Assets/Scripts/BlendCases.cs'

# name: [(length / width, direction in degrees), ...]
BASE = {
    'L.90.r1.5': [(1.5, 0), (1.5, 90)],
    'L.90.r1.25': [(1.25, 0), (1.25, 90)],
    'L.30.r1.5': [(1.5, 0), (1.5, 30)],
    'asym.90.r1.5_1.25': [(1.5, 0), (1.25, 90)],
    'asym.90.r2.5_1.25': [(2.5, 0), (1.25, 90)],
    'asym.90.r1.75_0.75': [(1.75, 0), (0.75, 90)],
    'asym.30.r1.5_1.25': [(1.5, 0), (1.25, 30)],
    'Z.stair.r1.5_1.25_1.75_1.25': [(1.5, 0), (1.25, 90), (1.75, 0), (1.25, 90)],
    'Z.u.r1.5_1.25_1.25_1.5': [(1.5, 0), (1.25, 90), (1.25, 180), (1.5, 270)],
    'Z.mid.r2.5_1.25_2.5': [(2.5, 0), (1.25, 90), (2.5, 0)],
    'Z.run.r1.25x3_1.25': [(1.25, 0), (1.25, 0), (1.25, 0), (1.25, 90)],
}
REVERSED = ['asym.90.r1.5_1.25', 'asym.90.r2.5_1.25', 'asym.30.r1.5_1.25',
            'Z.stair.r1.5_1.25_1.75_1.25', 'Z.run.r1.25x3_1.25']


def f32(x):
    return struct.unpack('<f', struct.pack('<f', x))[0]


def walk(segments):
    """The points (float32) of a polyline from START along the segments."""
    x, y = START
    points = [(x, y)]
    for ratio, degrees in segments:
        length = ratio*WIDTH
        a = math.radians(degrees)
        # Exact axis directions keep the 90-degree cases free of cos/sin rounding.
        c = {0: 1.0, 90: 0.0, 180: -1.0, 270: 0.0}.get(degrees % 360, math.cos(a))
        s = {0: 0.0, 90: 1.0, 180: 0.0, 270: -1.0}.get(degrees % 360, math.sin(a))
        x, y = x+length*c, y+length*s
        points.append((x, y))
    return [(f32(px), f32(py)) for px, py in points]


def cases():
    """name -> (points, ratios) in probe order."""
    out = {}
    for name, segments in BASE.items():
        out[name] = (walk(segments), [r for r, _ in segments])
    for name in REVERSED:
        points, ratios = out[name]
        out['rev.'+name] = (points[::-1], ratios[::-1])
    return out


def shortness(ratio):
    return min(1.0, max(0.0, 2.0/ratio-1.0))


def literal(x):
    text = repr(x)
    return text if text.count('.') or 'e' in text else text+'.0'


def source():
    lines = [
        '// Generated by tests/projects/lines/blend_cases.py; do not edit.',
        'using UnityEngine;',
        '',
        '/// <summary>The predeclared short-segment blend cases (blend_cases.py): name and points.</summary>',
        'static class BlendCases',
        '{',
        '    internal static readonly (string name, Vector3[] points)[] All =',
        '    {',
    ]
    for name, (points, _) in cases().items():
        ps = ', '.join(f'new Vector3({literal(x)}f, {literal(y)}f, 0f)' for x, y in points)
        lines.append(f'        ("{name}", new[] {{ {ps} }}),')
    lines += ['    };', '}', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--list', action='store_true')
    args = parser.parse_args()
    if args.list:
        for name, (points, ratios) in cases().items():
            print(f'blend.{name}: L/W {ratios} shortness {[round(shortness(r), 4) for r in ratios]} points {points}')
        return 0
    text = source()
    if args.check:
        current = OUTPUT.read_text() if OUTPUT.exists() else ''
        if current != text:
            print(f'{OUTPUT} is out of date; run {Path(__file__).name}', file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text)
    print('wrote', OUTPUT, len(cases()), 'cases')
    return 0


if __name__ == '__main__':
    sys.exit(main())
