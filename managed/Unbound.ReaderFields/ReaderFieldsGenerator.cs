using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Globalization;
using System.Linq;
using System.Text;
using System.Text.Json;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Operations;

namespace Unbound.ReaderFields;

/// <summary>Builds field declarations from the reader operations in the same compilation.
/// Field names and helper calls come from reader source, including branches that depend on
/// referenced assets. Doctor can inspect the declaration without creating runtime objects.</summary>
[Generator]
public sealed class ReaderFieldsGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterSourceOutput(context.CompilationProvider, (output, compilation) =>
        {
            var analysis = new Analysis(compilation);
            var rows = new SortedDictionary<string, State>(StringComparer.Ordinal);
            foreach (var tree in compilation.SyntaxTrees)
            {
                foreach (var method in tree.GetRoot().DescendantNodes().OfType<MethodDeclarationSyntax>())
                {
                    if (method.Body == null && method.ExpressionBody == null) continue;
                    bool nodeParameter = method.ParameterList.Parameters.Any(p => p.Type?.ToString().Contains("YNode", StringComparison.Ordinal) == true);
                    bool nodeType = method.Parent is ClassDeclarationSyntax owner && owner.Identifier.ValueText == "YNode";
                    if (!nodeParameter && !nodeType) continue;
                    var declaration = compilation.GetSemanticModel(tree).GetDeclaredSymbol(method);
                    if (declaration == null) continue;
                    var key = declaration.ContainingType.ToDisplayString() + "." + declaration.Name + "#" + declaration.Parameters.Length;
                    var read = analysis.Summary(method, declaration.Parameters, 0, new HashSet<SyntaxNode>());
                    if (!rows.TryGetValue(key, out var paths)) rows[key] = paths = new State();
                    paths.Reads.UnionWith(read.Reads);
                    paths.Returns.UnionWith(read.Returns);
                }
            }
            var json = "{" + string.Join(",", rows.Select(r => Quote(r.Key) + ":{\"reads\":[" + string.Join(",", r.Value.Reads.OrderBy(p => p, StringComparer.Ordinal).Select(Quote)) + "],\"returns\":[" + string.Join(",", r.Value.Returns.OrderBy(p => p, StringComparer.Ordinal).Select(Quote)) + "]}")) + "}";
            output.AddSource("ReaderFields.g.cs", "// <auto-generated/>\n[assembly: global::System.Reflection.AssemblyMetadataAttribute(\"Unbound.ReaderFields\", " + Quote(json) + ")]\n");
        });
    }

    static string Quote(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\r", "\\r").Replace("\n", "\\n").Replace("\t", "\\t").Replace("\u001f", "\\u001f") + "\"";

    sealed class State
    {
        internal readonly Dictionary<string, HashSet<string>> Nodes = new(StringComparer.Ordinal);
        internal readonly Dictionary<string, HashSet<string>> Strings = new(StringComparer.Ordinal);
        internal readonly HashSet<string> Reads = new(StringComparer.Ordinal);
        internal readonly HashSet<string> Returns = new(StringComparer.Ordinal);
        internal readonly Dictionary<string, ExpressionSyntax> Callables = new(StringComparer.Ordinal);
        internal void Bind(string name, IEnumerable<string> paths)
        {
            Nodes[name] = new(paths, StringComparer.Ordinal);
        }
        internal void Text(string name, IEnumerable<string> values)
        {
            Strings[name] = new(values, StringComparer.Ordinal);
        }
    }

    sealed class Analysis(Compilation compilation)
    {
        // Keep generated tables bounded. Exceeding either bound is an explicit incomplete
        // declaration, rather than broadening the fields assumed to have a reader.
        const int MaxCallDepth = 32;
        const int MaxExpandedLoopNames = 64;
        readonly Dictionary<SyntaxTree, SemanticModel> models = new();
        readonly Dictionary<SyntaxNode, State> summaries = new();
        Dictionary<string, State> imported;
        State Imported(IMethodSymbol method)
        {
            if (imported == null)
            {
                imported = new(StringComparer.Ordinal);
                foreach (var assembly in compilation.SourceModule.ReferencedAssemblySymbols)
                    foreach (var attribute in assembly.GetAttributes())
                    {
                        if (attribute.AttributeClass?.ToDisplayString() != "System.Reflection.AssemblyMetadataAttribute"
                            || attribute.ConstructorArguments.Length != 2 || attribute.ConstructorArguments[0].Value as string != "Unbound.ReaderFields") continue;
                        using var doc = JsonDocument.Parse((string)attribute.ConstructorArguments[1].Value);
                        foreach (var row in doc.RootElement.EnumerateObject())
                        {
                            var state = new State();
                            foreach (var path in row.Value.GetProperty("reads").EnumerateArray()) state.Reads.Add(path.GetString());
                            foreach (var path in row.Value.GetProperty("returns").EnumerateArray()) state.Returns.Add(path.GetString());
                            imported[row.Name] = state;
                        }
                    }
            }
            return imported.TryGetValue(method.ContainingType.ToDisplayString() + "." + method.Name + "#" + method.Parameters.Length, out var result) ? result : null;
        }
        SemanticModel Model(SyntaxNode node)
        {
            if (!models.TryGetValue(node.SyntaxTree, out var model)) models[node.SyntaxTree] = model = compilation.GetSemanticModel(node.SyntaxTree);
            return model;
        }
        static HashSet<string> Empty() => new(StringComparer.Ordinal);
        static HashSet<string> Set(string value) => new(StringComparer.Ordinal) { value };
        static HashSet<string> Union(params IEnumerable<string>[] values) => new(values.SelectMany(v => v), StringComparer.Ordinal);
        static bool HasNode(ITypeSymbol type) => type != null && (type.ToDisplayString() == "Unbound.Runtime.YNode" || type is IArrayTypeSymbol array && HasNode(array.ElementType)
            || type is INamedTypeSymbol named && named.TypeArguments.Any(HasNode));

        static bool HasText(ITypeSymbol type) => type?.SpecialType == SpecialType.System_String
            || type is IArrayTypeSymbol array && HasText(array.ElementType);

        internal State Summary(SyntaxNode method, ImmutableArray<IParameterSymbol> parameters, int depth, HashSet<SyntaxNode> stack)
        {
            if (summaries.TryGetValue(method, out var cached)) return cached;
            if (depth > MaxCallDepth || !stack.Add(method))
            {
                var incomplete = new State(); incomplete.Reads.Add("!unknown recursive reader declaration"); return incomplete;
            }
            var state = new State();
            for (int i = 0; i < parameters.Length; i++)
            {
                if (HasNode(parameters[i].Type)) state.Bind(parameters[i].Name, Set("@" + i));
                if (HasText(parameters[i].Type)) state.Text(parameters[i].Name, Set("§" + i));
            }
            Walk(method, state, depth, stack, method);
            stack.Remove(method);
            summaries[method] = state;
            return state;
        }

        static State Copy(State source)
        {
            var result = new State();
            foreach (var pair in source.Nodes) result.Bind(pair.Key, pair.Value);
            foreach (var pair in source.Strings) result.Text(pair.Key, pair.Value);
            foreach (var pair in source.Callables) result.Callables[pair.Key] = pair.Value;
            return result;
        }
        static void Merge(State target, params State[] branches)
        {
            foreach (var name in branches.SelectMany(b => b.Nodes.Keys).Distinct().ToArray())
                target.Bind(name, branches.Where(b => b.Nodes.ContainsKey(name)).SelectMany(b => b.Nodes[name]));
            foreach (var name in branches.SelectMany(b => b.Strings.Keys).Distinct().ToArray())
                target.Text(name, branches.Where(b => b.Strings.ContainsKey(name)).SelectMany(b => b.Strings[name]));
            foreach (var branch in branches) { target.Reads.UnionWith(branch.Reads); target.Returns.UnionWith(branch.Returns); }
        }

        void Walk(SyntaxNode node, State state, int depth, HashSet<SyntaxNode> stack, SyntaxNode root)
        {
            if (node is LocalFunctionStatementSyntax && node != root) return;
            switch (node)
            {
                case BlockSyntax block:
                    foreach (var statement in block.Statements)
                    {
                        Walk(statement, state, depth, stack, root);
                        if (statement is ReturnStatementSyntax or ThrowStatementSyntax) break;
                    }
                    return;
                case IfStatementSyntax branch:
                    Eval(branch.Condition, state, depth, stack);
                    var known = Model(branch.Condition).GetConstantValue(branch.Condition);
                    if (known.HasValue && known.Value is bool conditionValue)
                    {
                        if (conditionValue) Walk(branch.Statement, state, depth, stack, root);
                        else if (branch.Else != null) Walk(branch.Else.Statement, state, depth, stack, root);
                    }
                    else
                    {
                        var yes = Copy(state); var no = Copy(state);
                        Walk(branch.Statement, yes, depth, stack, root);
                        if (branch.Else != null) Walk(branch.Else.Statement, no, depth, stack, root);
                        Merge(state, yes, no);
                    }
                    return;
                case VariableDeclaratorSyntax variable:
                    if (variable.Initializer != null)
                    {
                        state.Bind(variable.Identifier.ValueText, Eval(variable.Initializer.Value, state, depth, stack));
                        state.Text(variable.Identifier.ValueText, Text(variable.Initializer.Value, state));
                    }
                    return;
                case AssignmentExpressionSyntax assignment:
                    // Index expressions and initializer members are not local-variable writes.
                    if (assignment.Left is ElementAccessExpressionSyntax indexed)
                    {
                        Eval(indexed.Expression, state, depth, stack);
                        foreach (var argument in indexed.ArgumentList.Arguments) Eval(argument.Expression, state, depth, stack);
                    }
                    else if (assignment.Left is MemberAccessExpressionSyntax target) Eval(target.Expression, state, depth, stack);
                    var assigned = Eval(assignment.Right, state, depth, stack);
                    if (assignment.Left is IdentifierNameSyntax local && assignment.Parent is not InitializerExpressionSyntax)
                        state.Bind(local.Identifier.ValueText, assigned);
                    return;
                case ForEachStatementSyntax loop:
                    var values = Eval(loop.Expression, state, depth, stack);
                    state.Bind(loop.Identifier.ValueText, values);
                    state.Text(loop.Identifier.ValueText, Text(loop.Expression, state));
                    Walk(loop.Statement, state, depth, stack, root);
                    return;
                case ForEachVariableStatementSyntax loop:
                    var items = Eval(loop.Expression, state, depth, stack);
                    foreach (var id in loop.Variable.DescendantNodesAndSelf().OfType<SingleVariableDesignationSyntax>()) state.Bind(id.Identifier.ValueText, items);
                    Walk(loop.Statement, state, depth, stack, root);
                    return;
                case ForStatementSyntax loop:
                    if (loop.Declaration != null)
                        foreach (var v in loop.Declaration.Variables) state.Text(v.Identifier.ValueText, LoopValues(loop, v));
                    if (loop.Condition != null) Eval(loop.Condition, state, depth, stack);
                    Walk(loop.Statement, state, depth, stack, root);
                    return;
                case ReturnStatementSyntax ret:
                    if (ret.Expression != null) state.Returns.UnionWith(Eval(ret.Expression, state, depth, stack));
                    return;
                case YieldStatementSyntax yield:
                    if (yield.Expression != null) state.Returns.UnionWith(Eval(yield.Expression, state, depth, stack));
                    return;
                case ArrowExpressionClauseSyntax arrow:
                    state.Returns.UnionWith(Eval(arrow.Expression, state, depth, stack));
                    return;
                case ExpressionSyntax expression:
                    Eval(expression, state, depth, stack);
                    return;
            }
            foreach (var child in node.ChildNodes()) Walk(child, state, depth, stack, root);
        }

        IEnumerable<string> LoopValues(ForStatementSyntax loop, VariableDeclaratorSyntax variable)
        {
            string name = variable.Identifier.ValueText;
            if (variable.Initializer == null || Model(variable.Initializer.Value).GetConstantValue(variable.Initializer.Value) is not { HasValue: true, Value: int start }
                || loop.Condition is not BinaryExpressionSyntax condition || !condition.IsKind(SyntaxKind.LessThanExpression)
                || condition.Left is not IdentifierNameSyntax id || id.Identifier.ValueText != name
                || Model(condition.Right).GetConstantValue(condition.Right) is not { HasValue: true, Value: int end }
                || loop.Incrementors.Count != 1) return new[] { "!unknown loop field names" };
            var increment = loop.Incrementors[0];
            int step = increment is PostfixUnaryExpressionSyntax post && post.IsKind(SyntaxKind.PostIncrementExpression) && post.Operand.ToString() == name
                || increment is PrefixUnaryExpressionSyntax pre && pre.IsKind(SyntaxKind.PreIncrementExpression) && pre.Operand.ToString() == name ? 1
                : increment is AssignmentExpressionSyntax assignment && assignment.IsKind(SyntaxKind.AddAssignmentExpression) && assignment.Left.ToString() == name
                    && Model(assignment.Right).GetConstantValue(assignment.Right) is { HasValue: true, Value: int amount } ? amount : 0;
            if (step <= 0 || (long)end - start > (long)MaxExpandedLoopNames * step) return new[] { "!unknown loop field names" };
            var values = new List<string>();
            for (long value = start; value < end; value += step) values.Add(value.ToString(CultureInfo.InvariantCulture));
            return values;
        }

        HashSet<string> Eval(ExpressionSyntax expression, State state, int depth, HashSet<SyntaxNode> stack, HashSet<string> receiver = null)
        {
            switch (expression)
            {
                case AnonymousFunctionExpressionSyntax: return Empty();
                case ThisExpressionSyntax: return Set("@this");
                case TupleExpressionSyntax tuple: return Union(tuple.Arguments.SelectMany(a => Eval(a.Expression, state, depth, stack)));
                case IdentifierNameSyntax name:
                    return state.Nodes.TryGetValue(name.Identifier.ValueText, out var paths) ? new(paths, StringComparer.Ordinal) : Empty();
                case ParenthesizedExpressionSyntax paren: return Eval(paren.Expression, state, depth, stack);
                case CastExpressionSyntax cast: return Eval(cast.Expression, state, depth, stack);
                case PostfixUnaryExpressionSyntax unary: return Eval(unary.Operand, state, depth, stack);
                case MemberAccessExpressionSyntax member:
                    var parent = Eval(member.Expression, state, depth, stack);
                    if (member.Name.Identifier.ValueText == "Scalar") { state.Reads.UnionWith(parent); return Empty(); }
                    if (member.Name.Identifier.ValueText == "Keys") return Empty();
                    return member.Name.Identifier.ValueText switch
                    {
                        "Values" => new(parent.Select(p => p + "\u001fk*"), StringComparer.Ordinal),
                        "Items" => new(parent.Select(p => p + "\u001fa"), StringComparer.Ordinal),
                        _ => parent,
                    };
                case ConditionalAccessExpressionSyntax conditional:
                    return Eval(conditional.WhenNotNull, state, depth, stack, Eval(conditional.Expression, state, depth, stack, receiver));
                case ConditionalExpressionSyntax conditional:
                    Eval(conditional.Condition, state, depth, stack);
                    return Union(Eval(conditional.WhenTrue, state, depth, stack), Eval(conditional.WhenFalse, state, depth, stack));
                case IsPatternExpressionSyntax pattern:
                    var matched = Eval(pattern.Expression, state, depth, stack);
                    foreach (var id in pattern.Pattern.DescendantNodesAndSelf().OfType<SingleVariableDesignationSyntax>()) state.Bind(id.Identifier.ValueText, matched);
                    return Empty();
                case ElementAccessExpressionSyntax element:
                    var source = Eval(element.Expression, state, depth, stack);
                    // YNode's string indexer, distinct from indexing Items/Values or collections.
                    if (Model(element.Expression).GetTypeInfo(element.Expression).Type?.ToDisplayString() == "Unbound.Runtime.YNode")
                        return Get(source, Text(element.ArgumentList.Arguments[0].Expression, state), state);
                    return source;
                case InvocationExpressionSyntax call:
                    return Invoke(call, state, depth, stack, receiver);
                case AssignmentExpressionSyntax assignment:
                    Walk(assignment, state, depth, stack, assignment);
                    return Eval(assignment.Right, state, depth, stack);
                default:
                    var result = Empty();
                    void Children(SyntaxNode parent)
                    {
                        foreach (var child in parent.ChildNodes())
                            if (child is ExpressionSyntax e) result.UnionWith(Eval(e, state, depth, stack));
                            else Children(child);
                    }
                    Children(expression);
                    return result;
            }
        }

        HashSet<string> Get(HashSet<string> receivers, HashSet<string> names, State state)
        {
            if (names.Count == 0) names.Add("!unknown");
            var paths = new HashSet<string>(receivers.SelectMany(p => names.Select(n => p + "\u001fk" + n)), StringComparer.Ordinal);
            state.Reads.UnionWith(paths);
            return paths;
        }

        HashSet<string> Invoke(InvocationExpressionSyntax call, State state, int depth, HashSet<SyntaxNode> stack, HashSet<string> receiver)
        {
            var operation = Model(call).GetOperation(call) as IInvocationOperation;
            var method = operation?.TargetMethod;
            receiver ??= call.Expression is MemberAccessExpressionSyntax access ? Eval(access.Expression, state, depth, stack) : Empty();
            var arguments = call.ArgumentList.Arguments.Select(a => Eval(a.Expression, state, depth, stack)).ToArray();
            if (method == null)
            {
                if (receiver.Count != 0) state.Reads.Add("!unknown dynamic reader invocation");
                return Empty();
            }
            if (method.MethodKind == MethodKind.DelegateInvoke && call.Expression is IdentifierNameSyntax callable && state.Callables.TryGetValue(callable.Identifier.ValueText, out var callback))
                return Callback(callback, arguments, state, depth, stack);
            // Collections retain node provenance; they do not consume a node's fields merely by storing it.
            if (method.ContainingNamespace.ToDisplayString() == "System.Collections.Generic" && method.Name is "Add" or "AddRange" or "Push" or "Enqueue"
                && call.Expression is MemberAccessExpressionSyntax collection && collection.Expression is IdentifierNameSyntax variable)
                state.Bind(variable.Identifier.ValueText, Union(receiver, arguments.SelectMany(a => a)));
            bool nodeMethod = method.ContainingType.ToDisplayString() == "Unbound.Runtime.YNode";
            if (nodeMethod && !method.IsStatic && receiver.Count == 0 && call.Expression is IdentifierNameSyntax or GenericNameSyntax) receiver = Set("@this");
            if (nodeMethod)
            {
                if (!method.IsStatic && receiver.Count == 0)
                    state.Reads.Add("!unknown receiver in " + method.Name);
                if (method.Name is "Get" or "TryGet")
                {
                    var got = Get(receiver, Text(call.ArgumentList.Arguments[0].Expression, state), state);
                    if (method.Name == "TryGet" && call.ArgumentList.Arguments.Count > 1)
                        foreach (var name in call.ArgumentList.Arguments[1].DescendantNodes().OfType<SingleVariableDesignationSyntax>()) state.Bind(name.Identifier.ValueText, got);
                    return method.Name == "Get" ? got : Empty();
                }
                if (method.Name == "Seq") return new(receiver.Select(p => p + "\u001fa"), StringComparer.Ordinal);
                if (method.Name is "AsString" or "AsLong" or "AsULong" or "AsDouble" or "AsFloat" or "AsInt" or "AsBool") { state.Reads.UnionWith(receiver); return Empty(); }
            }
            var definition = method.ReducedFrom ?? method;
            var declaration = definition.DeclaringSyntaxReferences.FirstOrDefault()?.GetSyntax();
            if (declaration is LocalFunctionStatementSyntax local && depth < MaxCallDepth && !stack.Contains(local))
            {
                var localState = Copy(state);
                for (int i = 0; i < method.Parameters.Length && i < arguments.Length; i++)
                {
                    localState.Bind(method.Parameters[i].Name, arguments[i]);
                    localState.Text(method.Parameters[i].Name, Text(call.ArgumentList.Arguments[i].Expression, state));
                    if (method.Parameters[i].Type.TypeKind == TypeKind.Delegate) localState.Callables[method.Parameters[i].Name] = call.ArgumentList.Arguments[i].Expression;
                }
                stack.Add(local);
                Walk(local, localState, depth + 1, stack, local);
                stack.Remove(local);
                state.Reads.UnionWith(localState.Reads);
                return HasNode(method.ReturnType) ? localState.Returns : Empty();
            }
            if (declaration != null && stack.Contains(declaration))
            {
                // Revisiting the same node domain adds no declarations: array indices are
                // already represented by their shared element path. Descending recursion needs
                // a different domain and is left explicitly incomplete.
                if (!definition.Parameters.Any(p => HasNode(p.Type)) && !nodeMethod
                    && !declaration.DescendantNodes().OfType<InvocationExpressionSyntax>().Any(i => Model(i).GetOperation(i) is IInvocationOperation op
                        && (op.TargetMethod.ContainingType.ToDisplayString() == "Unbound.Runtime.YNode" || op.TargetMethod.Parameters.Any(p => HasNode(p.Type)))))
                    return Empty();
                bool sameDomain = !nodeMethod || receiver.SetEquals(new[] { "@this" });
                for (int i = 0; i < definition.Parameters.Length; i++)
                {
                    if (HasNode(definition.Parameters[i].Type)) sameDomain &= i < arguments.Length && arguments[i].SetEquals(new[] { "@" + i });
                    if (HasText(definition.Parameters[i].Type)) sameDomain &= i < call.ArgumentList.Arguments.Count && Text(call.ArgumentList.Arguments[i].Expression, state).SetEquals(new[] { "§" + i });
                }
                if (!sameDomain) state.Reads.Add("!unknown descending reader recursion in " + definition.Name + ": " + string.Join(";", arguments.Select(a => string.Join(",", a))));
                return Empty();
            }
            var summary = declaration == null ? Imported(definition)
                : nodeMethod || method.Parameters.Any(p => HasNode(p.Type)) ? Summary(declaration, definition.Parameters, depth + 1, stack) : null;
            if (summary == null) return HasNode(method.ReturnType) ? Union(arguments.Concat(new[] { receiver }).ToArray()) : Empty();
            var nodeArguments = new Dictionary<int, HashSet<string>>();
            var stringArguments = new Dictionary<int, HashSet<string>>();
            for (int i = 0; i < definition.Parameters.Length; i++)
            {
                int argument = i;
                if (method.ReducedFrom != null) argument--;
                nodeArguments[i] = argument >= 0 && argument < arguments.Length ? arguments[argument] : receiver;
                stringArguments[i] = argument >= 0 && argument < call.ArgumentList.Arguments.Count ? Text(call.ArgumentList.Arguments[argument].Expression, state)
                    : definition.Parameters[i].HasExplicitDefaultValue && definition.Parameters[i].ExplicitDefaultValue is string defaultText ? Set(defaultText) : Empty();
            }
            // Instance YNode helpers use `this`; ordinary helper parameters use @N.
            HashSet<string> Expand(string path)
            {
                var expanded = Set(path);
                foreach (var pair in stringArguments)
                {
                    var values = pair.Value.Count == 0 ? Set("!unknown") : pair.Value;
                    expanded = new(expanded.SelectMany(p => values.Select(v => p.Replace("§" + pair.Key, v))), StringComparer.Ordinal);
                }
                var result = Empty();
                foreach (var p in expanded)
                {
                    if (p.StartsWith("!unknown", StringComparison.Ordinal)) { result.Add(p); continue; }
                    if (p.StartsWith("@this", StringComparison.Ordinal)) foreach (var r in receiver) result.Add(r + p.Substring(5));
                    else if (p.StartsWith("@", StringComparison.Ordinal))
                    {
                        int dot = p.IndexOf('\u001f', 1);
                        var number = p.Substring(1, (dot < 0 ? p.Length : dot) - 1);
                        if (int.TryParse(number, out var n) && nodeArguments.TryGetValue(n, out var input))
                            foreach (var r in input) result.Add(r + (dot < 0 ? "" : p.Substring(dot)));
                    }
                }
                return result;
            }
            foreach (var read in summary.Reads) state.Reads.UnionWith(Expand(read));
            return HasNode(method.ReturnType) ? Union(summary.Returns.SelectMany(Expand)) : Empty();
        }

        HashSet<string> Callback(ExpressionSyntax callback, HashSet<string>[] arguments, State state, int depth, HashSet<SyntaxNode> stack)
        {
            var local = Copy(state);
            SyntaxNode body;
            string[] names;
            if (callback is SimpleLambdaExpressionSyntax simple)
            {
                names = new[] { simple.Parameter.Identifier.ValueText }; body = simple.Body;
            }
            else if (callback is ParenthesizedLambdaExpressionSyntax lambda)
            {
                names = lambda.ParameterList.Parameters.Select(p => p.Identifier.ValueText).ToArray(); body = lambda.Body;
            }
            else
            {
                var target = Model(callback).GetMemberGroup(callback).OfType<IMethodSymbol>()
                    .FirstOrDefault(m => m.Parameters.Length == arguments.Length && m.Parameters.Any(p => HasNode(p.Type)));
                body = target?.DeclaringSyntaxReferences.FirstOrDefault()?.GetSyntax();
                if (body == null) { state.Reads.Add("!unknown reader callback"); return Empty(); }
                names = target.Parameters.Select(p => p.Name).ToArray();
            }
            for (int i = 0; i < names.Length && i < arguments.Length; i++) local.Bind(names[i], arguments[i]);
            if (depth > MaxCallDepth || !stack.Add(body)) { state.Reads.Add("!unknown recursive callback"); return Empty(); }
            if (body is ExpressionSyntax expression) local.Returns.UnionWith(Eval(expression, local, depth + 1, stack));
            else Walk(body, local, depth + 1, stack, body);
            stack.Remove(body);
            state.Reads.UnionWith(local.Reads);
            return local.Returns;
        }

        HashSet<string> Text(ExpressionSyntax expression, State state)
        {
            if (expression == null) return Empty();
            var constant = Model(expression).GetConstantValue(expression);
            if (constant.HasValue && constant.Value != null) return Set(Convert.ToString(constant.Value, CultureInfo.InvariantCulture));
            switch (expression)
            {
                case IdentifierNameSyntax name:
                    if (state.Strings.TryGetValue(name.Identifier.ValueText, out var values)) return new(values, StringComparer.Ordinal);
                    break;
                case ConditionalExpressionSyntax conditional: return Union(Text(conditional.WhenTrue, state), Text(conditional.WhenFalse, state));
                case InterpolatedStringExpressionSyntax interpolation:
                    var parts = Set("");
                    foreach (var content in interpolation.Contents)
                    {
                        var next = content is InterpolatedStringTextSyntax literal ? Set(literal.TextToken.ValueText)
                            : content is InterpolationSyntax item ? Text(item.Expression, state) : Empty();
                        if (next.Count == 0) next.Add("!unknown interpolated field name");
                        parts = new(parts.SelectMany(p => next.Select(n => p + n)), StringComparer.Ordinal);
                    }
                    return parts;
                case InvocationExpressionSyntax invocation when invocation.Expression is MemberAccessExpressionSyntax access && access.Name.Identifier.ValueText == "ToString":
                    return Text(access.Expression, state);
                case BinaryExpressionSyntax binary when binary.IsKind(SyntaxKind.AddExpression):
                    var left = Text(binary.Left, state); var right = Text(binary.Right, state);
                    if (left.Count == 0 || right.Count == 0) return Empty();
                    bool number = Model(binary).GetTypeInfo(binary).Type?.SpecialType != SpecialType.System_String;
                    return new(left.SelectMany(a => right.Select(b => number && int.TryParse(a, out var x) && int.TryParse(b, out var y) ? (x + y).ToString(CultureInfo.InvariantCulture) : a + b)), StringComparer.Ordinal);
                case ElementAccessExpressionSyntax element: return Text(element.Expression, state);
                case MemberAccessExpressionSyntax member when member.Name.Identifier.ValueText == "Keys": return Set("*");
                case InitializerExpressionSyntax initializer: return Union(initializer.Expressions.SelectMany(e => Text(e, state)));
                case ArrayCreationExpressionSyntax array when array.Initializer != null: return Union(array.Initializer.Expressions.SelectMany(e => Text(e, state)));
                case ImplicitArrayCreationExpressionSyntax array: return Union(array.Initializer.Expressions.SelectMany(e => Text(e, state)));
            }
            // Static field tables are part of the readers, rather than a second coverage list.
            if (Model(expression).GetOperation(expression) is IFieldReferenceOperation field)
            {
                var variable = field.Field.DeclaringSyntaxReferences.FirstOrDefault()?.GetSyntax() as VariableDeclaratorSyntax;
                if (variable?.Initializer != null && variable.Initializer.Value != expression) return Text(variable.Initializer.Value, state);
            }
            return Empty();
        }
    }
