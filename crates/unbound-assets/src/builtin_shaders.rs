//! Built-in shaders whose ShaderLab source Unity does not publish in its `builtin_shaders`
//! archive (UI Toolkit's renderer shaders): written out from the serialized shader the Editor
//! ships in `unity_builtin_extra` (its properties, tags, render state and keywords) around the
//! program of Unity's own include that defines its vertex and fragment functions.
use crate::serialized::SerializedFile;
use anyhow::{Context, Result};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use unbound_yaml::Value;

/// Bumped when the generated sources change.
const FORMAT_VERSION: u32 = 2;

/// The shaders written so, with the include (below the install's `CGIncludes`) that holds
/// their `vert` and `frag` programs.
const PROGRAMS: &[(&str, &str)] = &[("Hidden/Internal-UIRDefault", "Internal/UnityUIE.cginc")];

/// The name prefix of a shader's masked variant: its passes test and write the stencil buffer by
/// `_UIRStencilRef`, `_UIRStencilComp` and `_UIRStencilPass`, and write the colors of
/// `_UIRColorMask`.
pub const MASKED_PREFIX: &str = "Hidden/Unbound/Masked/";

/// Writes the shaders into `<cache>/builtin-shaders/generated-v<N>/<release>/` (once) and returns
/// that directory, to be indexed like the built-in shader sources. `unity_data` is the install's
/// `Editor/Data`.
pub fn write_generated(unity_data: &Path, cache_root: &Path, release: &str) -> Result<PathBuf> {
    let dir = cache_root
        .join("builtin-shaders")
        .join(format!("generated-v{FORMAT_VERSION}"))
        .join(release);
    if dir.join(".complete").is_file() {
        return Ok(dir);
    }
    let path = unity_data.join("Resources/unity_builtin_extra");
    let data = std::fs::read(&path).with_context(|| format!("reading {}", path.display()))?;
    let file = SerializedFile::parse(&data)?;
    std::fs::create_dir_all(&dir)?;
    for object in file.objects.iter().filter(|o| o.class_id == 48) {
        let Ok(shader) = file.read(object.path_id) else {
            continue;
        };
        let Some(parsed) = shader.get("m_ParsedForm") else {
            continue;
        };
        let name = parsed.get("m_Name").and_then(Value::as_str).unwrap_or("");
        let Some((_, include)) = PROGRAMS.iter().find(|(n, _)| *n == name) else {
            continue;
        };
        if !unity_data.join("CGIncludes").join(include).is_file() {
            tracing::warn!(
                "{name}: the install has no CGIncludes/{include}; the shader is not available"
            );
            continue;
        }
        let file_name = name.rsplit('/').next().unwrap_or(name);
        std::fs::write(
            dir.join(format!("{file_name}.shader")),
            shaderlab(parsed, include, None),
        )?;
        // The same with the stencil state UI Toolkit's renderer sets per draw when panels clip
        // to rounded rectangles (UIRenderDevice's stencil state), driven by material properties.
        let masked = format!("{MASKED_PREFIX}{name}");
        std::fs::write(
            dir.join(format!("{file_name} (masked).shader")),
            shaderlab(parsed, include, Some(&masked)),
        )?;
    }
    std::fs::write(dir.join(".complete"), "")?;
    Ok(dir)
}

/// The ShaderLab source of a serialized shader's parsed form, its passes running the `vert` and
/// `frag` of `include`.
pub fn shaderlab(parsed: &Value, include: &str, masked: Option<&str>) -> String {
    let mut s = String::new();
    let name = masked.unwrap_or_else(|| parsed.get("m_Name").and_then(Value::as_str).unwrap_or(""));
    let _ = writeln!(
        s,
        "// Generated by Unbound from Unity's serialized shader (unity_builtin_extra)."
    );
    let _ = writeln!(s, "Shader \"{name}\"\n{{");
    let _ = writeln!(s, "    Properties\n    {{");
    for p in seq(parsed.path("m_PropInfo.m_Props")) {
        let pname = str_of(p, "m_Name");
        let desc = str_of(p, "m_Description");
        let d = |i: usize| num(p, &format!("m_DefValue[{i}]"));
        let decl = match int(p, "m_Type") {
            0 => format!("Color) = ({}, {}, {}, {})", d(0), d(1), d(2), d(3)),
            1 => format!("Vector) = ({}, {}, {}, {})", d(0), d(1), d(2), d(3)),
            2 => format!("Float) = {}", d(0)),
            3 => format!("Range({}, {})) = {}", d(1), d(2), d(0)),
            4 => {
                let dim = match p.path("m_DefTexture.m_TexDim").and_then(Value::as_i64) {
                    Some(3) => "3D",
                    Some(4) => "Cube",
                    Some(5) => "2DArray",
                    _ => "2D",
                };
                let default = p
                    .path("m_DefTexture.m_DefaultName")
                    .and_then(Value::as_str)
                    .unwrap_or("");
                format!("{dim}) = \"{default}\" {{}}")
            }
            _ => format!("Int) = {}", d(0)),
        };
        let _ = writeln!(s, "        {pname} (\"{desc}\", {decl}");
    }
    if masked.is_some() {
        let _ = writeln!(s, "        _UIRStencilRef (\"Stencil Ref\", Float) = 0");
        let _ = writeln!(
            s,
            "        _UIRStencilComp (\"Stencil Comparison\", Float) = 8"
        );
        let _ = writeln!(s, "        _UIRStencilPass (\"Stencil Pass\", Float) = 0");
        let _ = writeln!(s, "        _UIRColorMask (\"Color Mask\", Float) = 15");
    }
    let _ = writeln!(s, "    }}");
    let keywords: Vec<&str> = seq(parsed.get("m_KeywordNames"))
        .iter()
        .filter_map(Value::as_str)
        .filter(|k| !k.starts_with("STEREO_") && !k.starts_with("UNITY_SINGLE_PASS_STEREO"))
        .collect();
    for sub in seq(parsed.get("m_SubShaders")) {
        let _ = writeln!(s, "    SubShader\n    {{");
        write_tags(&mut s, sub.get("m_Tags"), "        ");
        let lod = int(sub, "m_LOD");
        if lod != 0 {
            let _ = writeln!(s, "        LOD {lod}");
        }
        for pass in seq(sub.get("m_Passes")) {
            let _ = writeln!(s, "        Pass\n        {{");
            let state = pass.get("m_State");
            if let Some(state) = state {
                let pass_name = str_of(state, "m_Name");
                if !pass_name.is_empty() {
                    let _ = writeln!(s, "            Name \"{pass_name}\"");
                }
                write_tags(&mut s, state.get("m_Tags"), "            ");
                write_state(&mut s, state, "            ");
                if masked.is_some() {
                    let _ = writeln!(s, "            ColorMask [_UIRColorMask]");
                    let _ = writeln!(
                        s,
                        "            Stencil {{ Ref [_UIRStencilRef] ReadMask 255 WriteMask 255 Comp [_UIRStencilComp] Pass [_UIRStencilPass] }}"
                    );
                }
            }
            let _ = writeln!(s, "            CGPROGRAM");
            let _ = writeln!(s, "            #pragma vertex vert");
            let _ = writeln!(s, "            #pragma fragment frag");
            for k in &keywords {
                let _ = writeln!(s, "            #pragma multi_compile_local __ {k}");
            }
            let _ = writeln!(s, "            #include \"{include}\"");
            let _ = writeln!(s, "            ENDCG");
            let _ = writeln!(s, "        }}");
        }
        let _ = writeln!(s, "    }}");
    }
    let _ = writeln!(s, "}}");
    s
}

fn seq(v: Option<&Value>) -> &[Value] {
    v.and_then(Value::as_seq).unwrap_or(&[])
}

fn str_of<'a>(v: &'a Value, key: &str) -> &'a str {
    v.get(key).and_then(Value::as_str).unwrap_or("")
}

fn num(v: &Value, key: &str) -> f64 {
    v.get(key).and_then(Value::as_f64).unwrap_or(0.0)
}

fn int(v: &Value, key: &str) -> i64 {
    v.get(key).and_then(Value::as_i64).unwrap_or(0)
}

/// Tags as Unity spells them in sources (the serialized form upper-cases some names).
fn write_tags(s: &mut String, tags: Option<&Value>, indent: &str) {
    let tags = seq(tags.and_then(|t| t.get("tags")));
    if tags.is_empty() {
        return;
    }
    let _ = write!(s, "{indent}Tags {{");
    for t in tags {
        let key = match str_of(t, "first") {
            "QUEUE" => "Queue",
            "IGNOREPROJECTOR" => "IgnoreProjector",
            "RENDERTYPE" => "RenderType",
            "LIGHTMODE" => "LightMode",
            other => other,
        };
        let _ = write!(s, " \"{key}\"=\"{}\"", str_of(t, "second"));
    }
    let _ = writeln!(s, " }}");
}

/// A state value: its number, or `[property]` when a property drives it.
fn value(v: Option<&Value>, names: fn(i64) -> &'static str) -> String {
    let Some(v) = v else {
        return String::new();
    };
    let name = str_of(v, "name");
    if !name.is_empty() && name != "<noninit>" {
        return format!("[{name}]");
    }
    names(num(v, "val") as i64).to_string()
}

fn write_state(s: &mut String, state: &Value, indent: &str) {
    const BLEND: [&str; 11] = [
        "Zero",
        "One",
        "DstColor",
        "SrcColor",
        "OneMinusDstColor",
        "SrcAlpha",
        "OneMinusSrcColor",
        "DstAlpha",
        "OneMinusDstAlpha",
        "SrcAlphaSaturate",
        "OneMinusSrcAlpha",
    ];
    const COMPARE: [&str; 9] = [
        "Disabled", "Never", "Less", "Equal", "LEqual", "Greater", "NotEqual", "GEqual", "Always",
    ];
    const STENCIL_OP: [&str; 8] = [
        "Keep", "Zero", "Replace", "IncrSat", "DecrSat", "Invert", "IncrWrap", "DecrWrap",
    ];
    const BLEND_OP: [&str; 5] = ["Add", "Sub", "RevSub", "Min", "Max"];
    fn pick(table: &'static [&'static str], i: i64) -> &'static str {
        table.get(i.max(0) as usize).copied().unwrap_or(table[0])
    }
    let get = |k: &str| state.get(k);
    if let Some(b) = get("rtBlend0") {
        let f = |k: &str| value(b.get(k), |i| pick(&BLEND, i));
        let (src, dst, src_a, dst_a) = (
            f("srcBlend"),
            f("destBlend"),
            f("srcBlendAlpha"),
            f("destBlendAlpha"),
        );
        if src == "One" && dst == "Zero" && src_a == "One" && dst_a == "Zero" {
            let _ = writeln!(s, "{indent}Blend Off");
        } else {
            let _ = writeln!(s, "{indent}Blend {src} {dst}, {src_a} {dst_a}");
        }
        let op = value(b.get("blendOp"), |i| pick(&BLEND_OP, i));
        let op_a = value(b.get("blendOpAlpha"), |i| pick(&BLEND_OP, i));
        if op != "Add" || op_a != "Add" {
            let _ = writeln!(s, "{indent}BlendOp {op}, {op_a}");
        }
        let mask = b.get("colMask").map(|m| num(m, "val") as i64).unwrap_or(15);
        if mask != 15 {
            let mut letters = String::new();
            for (bit, l) in [(8, 'R'), (4, 'G'), (2, 'B'), (1, 'A')] {
                if mask & bit != 0 {
                    letters.push(l);
                }
            }
            let _ = writeln!(
                s,
                "{indent}ColorMask {}",
                if letters.is_empty() {
                    "0".into()
                } else {
                    letters
                }
            );
        }
    }
    let _ = writeln!(
        s,
        "{indent}ZTest {}",
        value(get("zTest"), |i| pick(&COMPARE, i))
    );
    let _ = writeln!(
        s,
        "{indent}ZWrite {}",
        value(get("zWrite"), |i| if i != 0 { "On" } else { "Off" })
    );
    let _ = writeln!(
        s,
        "{indent}Cull {}",
        value(get("culling"), |i| pick(&["Off", "Front", "Back"], i))
    );
    let factor = get("offsetFactor").map(|v| num(v, "val")).unwrap_or(0.0);
    let units = get("offsetUnits").map(|v| num(v, "val")).unwrap_or(0.0);
    if factor != 0.0 || units != 0.0 {
        let _ = writeln!(s, "{indent}Offset {factor}, {units}");
    }
    let stencil_ref = get("stencilRef").map(|v| num(v, "val")).unwrap_or(0.0);
    let op = get("stencilOp");
    let comp = op
        .and_then(|o| o.get("comp"))
        .map(|v| num(v, "val") as i64)
        .unwrap_or(8);
    let pass = op
        .and_then(|o| o.get("pass"))
        .map(|v| num(v, "val") as i64)
        .unwrap_or(0);
    let fail = op
        .and_then(|o| o.get("fail"))
        .map(|v| num(v, "val") as i64)
        .unwrap_or(0);
    let zfail = op
        .and_then(|o| o.get("zFail"))
        .map(|v| num(v, "val") as i64)
        .unwrap_or(0);
    if comp != 8 || pass != 0 || fail != 0 || zfail != 0 || stencil_ref != 0.0 {
        let read = get("stencilReadMask")
            .map(|v| num(v, "val"))
            .unwrap_or(255.0);
        let write = get("stencilWriteMask")
            .map(|v| num(v, "val"))
            .unwrap_or(255.0);
        let _ = writeln!(
            s,
            "{indent}Stencil {{ Ref {stencil_ref} ReadMask {read} WriteMask {write} Comp {} Pass {} Fail {} ZFail {} }}",
            pick(&COMPARE, comp),
            pick(&STENCIL_OP, pass),
            pick(&STENCIL_OP, fail),
            pick(&STENCIL_OP, zfail)
        );
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// UI Toolkit's default shader of the installed 6000.0.71f1 (skipped without it).
    #[test]
    fn the_ui_toolkit_shader_is_written_from_its_serialized_form() {
        let Some(home) = std::env::var_os("HOME") else {
            return;
        };
        let file = Path::new(&home)
            .join("Unity/Hub/Editor/6000.0.71f1/Editor/Data/Resources/unity_builtin_extra");
        let Ok(bytes) = std::fs::read(&file) else {
            eprintln!("no 6000.0.71f1 install: skipped");
            return;
        };
        let file = SerializedFile::parse(&bytes).unwrap();
        let shader = file.read(9100).unwrap();
        let source = shaderlab(
            shader.get("m_ParsedForm").unwrap(),
            "Internal/UnityUIE.cginc",
            None,
        );
        assert!(
            source.contains("Shader \"Hidden/Internal-UIRDefault\""),
            "{source}"
        );
        assert!(
            source.contains("_MainTex (\"Atlas\", 2D) = \"white\" {}"),
            "{source}"
        );
        assert!(
            source.contains("Blend SrcAlpha OneMinusSrcAlpha, One OneMinusSrcAlpha"),
            "{source}"
        );
        assert!(source.contains("ZTest LEqual\n"), "{source}");
        assert!(source.contains("ZWrite Off\n"), "{source}");
        assert!(source.contains("Cull Off\n"), "{source}");
        assert!(source.contains("\"Queue\"=\"Transparent\""), "{source}");
        assert!(
            source.contains("#pragma multi_compile_local __ UIE_FORCE_GAMMA"),
            "{source}"
        );
        assert!(!source.contains("Stencil"), "{source}");
    }
}
