//! Built-in shaders whose ShaderLab source Unity does not publish in its `builtin_shaders`
//! archive (UI Toolkit's renderer shaders): written out from the serialized shader the Editor
//! ships in `unity_builtin_extra` (its properties, tags, render state and keywords) around the
//! program of Unity's own include that defines its vertex and fragment functions.
use crate::serialized::SerializedFile;
use anyhow::{Context, Result};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use unbound_yaml::Value;

/// Bumped when the generated sources change.
const FORMAT_VERSION: u32 = 2;

/// The shaders written so, with the include (below the install's `CGIncludes`) that holds
/// their `vert` and `frag` programs.
const PROGRAMS: &[(&str, &str)] = &[("Hidden/Internal-UIRDefault", "Internal/UnityUIE.cginc")];

/// The name prefix of a shader's masked variant: its passes test and write the stencil buffer by
/// `_UIRStencilRef`, `_UIRStencilComp` and `_UIRStencilPass`, and write the colors of
/// `_UIRColorMask`.
pub const MASKED_PREFIX: &str = "Hidden/Unbound/Masked/";

/// Writes the shaders into `<cache>/builtin-shaders/generated-v<N>/<release>/` (once) and returns
/// that directory, to be indexed like the built-in shader sources. `unity_data` is the install's
/// `Editor/Data`.
pub fn write_generated(unity_data: &Path, cache_root: &Path, release: &str) -> Result<PathBuf> {
    let dir = cache_root
        .join("builtin-shaders")
        .join(format!("generated-v{FORMAT_VERSION}"))
        .join(release);
    if dir.join(".complete").is_file() {
        return Ok(dir);
    }
    let path = unity_data.join("Resources/unity_builtin_extra");
    let data = std::fs::read(&path).with_context(|| format!("reading {}", path.display()))?;
    let file = SerializedFile::parse(&data)?;
    std::fs::create_dir_all(&dir)?;
    for object in file.objects.iter().filter(|o| o.class_id == 48) {
        let Ok(shader) = file.read(object.path_id) else {
            continue;
        };
        let Some(parsed) = shader.get("m_ParsedForm") else {
            continue;
        };
        let name = parsed.get("m_Name").and_then(Value::as_str).unwrap_or("");
        let Some((_, include)) = PROGRAMS.iter().find(|(n, _)| *n == name) else {
            continue;
        };
        if !unity_data.join("CGIncludes").join(include).is_file() {
            tracing::warn!(
                "{name}: the install has no CGIncludes/{include}; the shader is not available"
            );
            continue;
        }
        let file_name = name.rsplit('/').next().unwrap_or(name);
        std::fs::write(
            dir.join(format!("{file_name}.shader")),
            shaderlab(parsed, include, None),
        )?;
        // The same with the stencil state UI Toolkit's renderer sets per draw when panels clip
        // to rounded rectangles (UIRenderDevice's stencil state), driven by material properties.
        let masked = format!("{MASKED_PREFIX}{name}");
        std::fs::write(
            dir.join(format!("{file_name} (masked).shader")),
            shaderlab(parsed, include, Some(&masked)),
        )?;
    }
    std::fs::write(dir.join(".complete"), "")?;
    Ok(dir)
}

/// The ShaderLab source of a serialized shader's parsed form, its passes running the `vert` and
/// `frag` of `include`.
pub fn shaderlab(parsed: &Value, include: &str, masked: Option<&str>) -> String {
    let mut s = String::new();
    let name = masked.unwrap_or_else(|| parsed.get("m_Name").and_then(Value::as_str).unwrap_or(""));
    let _ = writeln!(
        s,
        "// Generated by Unbound from Unity's serialized shader (unity_builtin_extra)."
    );
    let _ = writeln!(s, "Shader \"{name}\"\n{{");
    let _ = writeln!(s, "    Properties\n    {{");
    for p in seq(parsed.path("m_PropInfo.m_Props")) {
        let pname = str_of(p, "m_Name");
        let desc = str_of(p, "m_Description");
        let d = |i: usize| num(p, &format!("m_DefValue[{i}]"));
        let decl = match int(p, "m_Type") {
            0 => format!("Color) = ({}, {}, {}, {})", d(0), d(1), d(2), d(3)),
            1 => format!("Vector) = ({}, {}, {}, {})", d(0), d(1), d(2), d(3)),
            2 => format!("Float) = {}", d(0)),
            3 => format!("Range({}, {})) = {}", d(1), d(2), d(0)),
            4 => {
                let dim = match p.path("m_DefTexture.m_TexDim").and_then(Value::as_i64) {
                    Some(3) => "3D",
                    Some(4) => "Cube",
                    Some(5) => "2DArray",
                    _ => "2D",
                };
                let default = p
                    .path("m_DefTexture.m_DefaultName")
                    .and_then(Value::as_str)
                    .unwrap_or("");
                format!("{dim}) = \"{default}\" {{}}")
            }
            _ => format!("Int) = {}", d(0)),
        };
        let _ = writeln!(s, "        {pname} (\"{desc}\", {decl}");
    }
    if masked.is_some() {
        let _ = writeln!(s, "        _UIRStencilRef (\"Stencil Ref\", Float) = 0");
        let _ = writeln!(
            s,
            "        _UIRStencilComp (\"Stencil Comparison\", Float) = 8"
        );
        let _ = writeln!(s, "        _UIRStencilPass (\"Stencil Pass\", Float) = 0");
        let _ = writeln!(s, "        _UIRColorMask (\"Color Mask\", Float) = 15");
    }
    let _ = writeln!(s, "    }}");
    let keywords: Vec<&str> = seq(parsed.get("m_KeywordNames"))
        .iter()
        .filter_map(Value::as_str)
        .filter(|k| !k.starts_with("STEREO_") && !k.starts_with("UNITY_SINGLE_PASS_STEREO"))
        .collect();
    for sub in seq(parsed.get("m_SubShaders")) {
        let _ = writeln!(s, "    SubShader\n    {{");
        write_tags(&mut s, sub.get("m_Tags"), "        ");
        let lod = int(sub, "m_LOD");
        if lod != 0 {
            let _ = writeln!(s, "        LOD {lod}");
        }
        for pass in seq(sub.get("m_Passes")) {
            let _ = writeln!(s, "        Pass\n        {{");
            let state = pass.get("m_State");
            if let Some(state) = state {
                let pass_name = str_of(state, "m_Name");
                if !pass_name.is_empty() {
                    let _ = writeln!(s, "            Name \"{pass_name}\"");
                }
                write_tags(&mut s, state.get("m_Tags"), "            ");
                write_state(&mut s, state, "            ");
                if masked.is_some() {
                    let _ = writeln!(s, "            ColorMask [_UIRColorMask]");
                    let _ = writeln!(
                        s,
                        "            Stencil {{ Ref [_UIRStencilRef] ReadMask 255 WriteMask 255 Comp [_UIRStencilComp] Pass [_UIRStencilPass] }}"
                    );
                }
            }
            let _ = writeln!(s, "            CGPROGRAM");
            let _ = writeln!(s, "            #pragma vertex vert");
            let _ = writeln!(s, "            #pragma fragment frag");
            for k in &keywords {
                let _ = writeln!(s, "            #pragma multi_compile_local __ {k}");
            }
            let _ = writeln!(s, "            #include \"{include}\"");
            let _ = writeln!(s, "            ENDCG");
            let _ = writeln!(s, "        }}");
        }
        let _ = writeln!(s, "    }}");
    }
    let _ = writeln!(s, "}}");
    s
}

fn seq(v: Option<&Value>) -> &[Value] {
    v.and_then(Value::as_seq).unwrap_or(&[])
}

fn str_of<'a>(v: &'a Value, key: &str) -> &'a str {
    v.get(key).and_then(Value::as_str).unwrap_or("")
}

fn num(v: &Value, key: &str) -> f64 {
    v.get(key).and_then(Value::as_f64).unwrap_or(0.0)
}

fn int(v: &Value, key: &str) -> i64 {
    v.get(key).and_then(Value::as_i64).unwrap_or(0)
}

/// Tags as Unity spells them in sources (the serialized form upper-cases some names).
fn write_tags(s: &mut String, tags: Option<&Value>, indent: &str) {
    let tags = seq(tags.and_then(|t| t.get("tags")));
    if tags.is_empty() {
        return;
    }
    let _ = write!(s, "{indent}Tags {{");
    for t in tags {
        let key = match str_of(t, "first") {
            "QUEUE" => "Queue",
            "IGNOREPROJECTOR" => "IgnoreProjector",
            "RENDERTYPE" => "RenderType",
            "LIGHTMODE" => "LightMode",
            other => other,
        };
        let _ = write!(s, " \"{key}\"=\"{}\"", str_of(t, "second"));
    }
    let _ = writeln!(s, " }}");
}

/// A state value: its number, or `[property]` when a property drives it.
fn value(v: Option<&Value>, names: fn(i64) -> &'static str) -> String {
    let Some(v) = v else {
        return String::new();
    };
    let name = str_of(v, "name");
    if !name.is_empty() && name != "<noninit>" {
        return format!("[{name}]");
    }
    names(num(v, "val") as i64).to_string()
}

fn write_state(s: &mut String, state: &Value, indent: &str) {
    const BLEND: [&str; 11] = [
        "Zero",
        "One",
        "DstColor",
        "SrcColor",
        "OneMinusDstColor",
        "SrcAlpha",
        "OneMinusSrcColor",
        "DstAlpha",
        "OneMinusDstAlpha",
        "SrcAlphaSaturate",
        "OneMinusSrcAlpha",
    ];
    const COMPARE: [&str; 9] = [
        "Disabled", "Never", "Less", "Equal", "LEqual", "Greater", "NotEqual", "GEqual", "Always",
    ];
    const STENCIL_OP: [&str; 8] = [
        "Keep", "Zero", "Replace", "IncrSat", "DecrSat", "Invert", "IncrWrap", "DecrWrap",
    ];
    const BLEND_OP: [&str; 5] = ["Add", "Sub", "RevSub", "Min", "Max"];
    fn pick(table: &'static [&'static str], i: i64) -> &'static str {
        table.get(i.max(0) as usize).copied().unwrap_or(table[0])
    }
    let get = |k: &str| state.get(k);
    if let Some(b) = get("rtBlend0") {
        let f = |k: &str| value(b.get(k), |i| pick(&BLEND, i));
        let (src, dst, src_a, dst_a) = (
            f("srcBlend"),
            f("destBlend"),
            f("srcBlendAlpha"),
            f("destBlendAlpha"),
        );
        if src == "One" && dst == "Zero" && src_a == "One" && dst_a == "Zero" {
            let _ = writeln!(s, "{indent}Blend Off");
        } else {
            let _ = writeln!(s, "{indent}Blend {src} {dst}, {src_a} {dst_a}");
        }
        let op = value(b.get("blendOp"), |i| pick(&BLEND_OP, i));
        let op_a = value(b.get("blendOpAlpha"), |i| pick(&BLEND_OP, i));
        if op != "Add" || op_a != "Add" {
            let _ = writeln!(s, "{indent}BlendOp {op}, {op_a}");
        }
        let mask = b.get("colMask").map(|m| num(m, "val") as i64).unwrap_or(15);
        if mask != 15 {
            let mut letters = String::new();
            for (bit, l) in [(8, 'R'), (4, 'G'), (2, 'B'), (1, 'A')] {
                if mask & bit != 0 {
                    letters.push(l);
                }
            }
            let _ = writeln!(
                s,
                "{indent}ColorMask {}",
                if letters.is_empty() {
                    "0".into()
                } else {
                    letters
                }
            );
        }
    }
    let _ = writeln!(
        s,
        "{indent}ZTest {}",
        value(get("zTest"), |i| pick(&COMPARE, i))
    );
    let _ = writeln!(
        s,
        "{indent}ZWrite {}",
        value(get("zWrite"), |i| if i != 0 { "On" } else { "Off" })
    );
    let _ = writeln!(
        s,
        "{indent}Cull {}",
        value(get("culling"), |i| pick(&["Off", "Front", "Back"], i))
    );
    let factor = get("offsetFactor").map(|v| num(v, "val")).unwrap_or(0.0);
    let units = get("offsetUnits").map(|v| num(v, "val")).unwrap_or(0.0);
    if factor != 0.0 || units != 0.0 {
        let _ = writeln!(s, "{indent}Offset {factor}, {units}");
    }
    let stencil_ref = get("stencilRef").map(|v| num(v, "val")).unwrap_or(0.0);
    let op = get("stencilOp");
    let comp = op
        .and_then(|o| o.get("comp"))
        .map(|v| num(v, "val") as i64)
        .unwrap_or(8);
    let pass = op
        .and_then(|o| o.get("pass"))
        .map(|v| num(v, "val") as i64)
        .unwrap_or(0);
    let fail = op
        .and_then(|o| o.get("fail"))
        .map(|v| num(v, "val") as i64)
        .unwrap_or(0);
    let zfail = op
        .and_then(|o| o.get("zFail"))
        .map(|v| num(v, "val") as i64)
        .unwrap_or(0);
    if comp != 8 || pass != 0 || fail != 0 || zfail != 0 || stencil_ref != 0.0 {
        let read = get("stencilReadMask")
            .map(|v| num(v, "val"))
            .unwrap_or(255.0);
        let write = get("stencilWriteMask")
            .map(|v| num(v, "val"))
            .unwrap_or(255.0);
        let _ = writeln!(
            s,
            "{indent}Stencil {{ Ref {stencil_ref} ReadMask {read} WriteMask {write} Comp {} Pass {} Fail {} ZFail {} }}",
            pick(&COMPARE, comp),
            pick(&STENCIL_OP, pass),
            pick(&STENCIL_OP, fail),
            pick(&STENCIL_OP, zfail)
        );
    }
}

/// What a built-in shader declares, as Unity's serialized shader in the Editor's resources has
/// it: its SubShaders (tags and passes with their tags, names and values as Unity stores them),
/// its keywords (names in its keyword space's order, local, dynamic) and its `Fallback`. This is
/// Unity's own data for the install's release, not a rule of Unbound's.
#[derive(Debug, Clone, Default, PartialEq, serde::Serialize, serde::Deserialize)]
pub struct Declarations {
    pub subshaders: Vec<DeclaredSubShader>,
    pub keywords: Vec<DeclaredKeyword>,
    /// `Fallback` (empty: none).
    pub fallback: String,
}

#[derive(Debug, Clone, Default, PartialEq, serde::Serialize, serde::Deserialize)]
pub struct DeclaredSubShader {
    pub tags: Vec<(String, String)>,
    pub passes: Vec<DeclaredPass>,
    /// Its `LOD` as Unity serialized it (`m_LOD`; 0 when it declares none).
    pub lod: u32,
}

#[derive(Debug, Clone, Default, PartialEq, serde::Serialize, serde::Deserialize)]
pub struct DeclaredPass {
    pub name: String,
    pub tags: Vec<(String, String)>,
    /// The `UsePass` target (`"Shader/PASS"`) of a pass no shader in the resources resolves
    /// (empty for every other pass: a resolved `UsePass` is the named pass, its name and tags).
    pub use_pass: String,
}

#[derive(Debug, Clone, Default, PartialEq, serde::Serialize, serde::Deserialize)]
pub struct DeclaredKeyword {
    pub name: String,
    pub local: bool,
    pub dynamic: bool,
}

/// Every built-in shader's declarations, by name.
pub type DeclarationMap = std::collections::BTreeMap<String, Declarations>;

/// Bumped when [`Declarations`], how it is read ([`read_declarations`]), the entry layout or the
/// serialized-file reader's handling of shaders' parsed forms changes. The cache is ours (not
/// the import cache, not the texture cache): an entry is keyed by this version and the resource
/// files' bytes, and carries both, so a stale or foreign entry is never used. 3: SubShaders
/// carry their LOD ([`DeclaredSubShader::lod`]).
const DECLARATIONS_VERSION: u32 = 3;

/// Magic of a declarations cache entry: then the version (u32 LE), the 32-byte input key and the
/// postcard payload.
const DECLARATIONS_MAGIC: &[u8; 4] = b"UBSD";

/// The resource files the built-in shaders' serialized forms are read from (`unity_data` is the
/// install's `Editor/Data`).
pub fn declaration_sources(unity_data: &Path) -> [PathBuf; 2] {
    [
        unity_data.join("Resources/unity_builtin_extra"),
        unity_data.join("Resources/unity default resources"),
    ]
}

/// The cache key of the files' exact bytes under [`DECLARATIONS_VERSION`] (streamed: the files
/// are large and a cache hit does not need them in memory).
pub fn declarations_key(files: &[PathBuf]) -> Result<[u8; 32]> {
    let mut hasher = blake3::Hasher::new();
    hasher.update(DECLARATIONS_MAGIC);
    hasher.update(&DECLARATIONS_VERSION.to_le_bytes());
    for path in files {
        let mut file =
            std::fs::File::open(path).with_context(|| format!("reading {}", path.display()))?;
        let len = file
            .metadata()
            .with_context(|| format!("reading {}", path.display()))?
            .len();
        hasher.update(&len.to_le_bytes());
        let copied = std::io::copy(&mut file, &mut hasher)
            .with_context(|| format!("reading {}", path.display()))?;
        if copied != len {
            anyhow::bail!("{} changed while it was read", path.display());
        }
    }
    Ok(*hasher.finalize().as_bytes())
}

/// Every built-in shader's [`Declarations`] by name, from the install's resource files. Read
/// once per content of those files and kept in `<cache>/builtin-shaders/declarations-v<N>/`.
/// An error (a file missing or unreadable) is not cached: the next call tries again.
pub fn declarations(unity_data: &Path, cache_root: &Path) -> Result<DeclarationMap> {
    let files = declaration_sources(unity_data);
    let key = declarations_key(&files)?;
    let cached = declarations_entry_path(cache_root, &key);
    if let Some(map) = read_declarations_entry(&cached, &key) {
        return Ok(map);
    }
    let mut map = DeclarationMap::new();
    for path in &files {
        let data = std::fs::read(path).with_context(|| format!("reading {}", path.display()))?;
        let file =
            SerializedFile::parse(&data).with_context(|| format!("reading {}", path.display()))?;
        for object in file.objects.iter().filter(|o| o.class_id == 48) {
            let Ok(shader) = file.read(object.path_id) else {
                continue;
            };
            let Some(parsed) = shader.get("m_ParsedForm") else {
                continue;
            };
            let name = str_of(parsed, "m_Name").to_string();
            if !name.is_empty() {
                map.entry(name).or_insert_with(|| read_declarations(parsed));
            }
        }
    }
    resolve_use_passes(&mut map);
    // The inputs must not have changed while they were read (else the entry would be keyed by
    // bytes it was not read from).
    if declarations_key(&files)? != key {
        anyhow::bail!("Unity's built-in resources changed while they were read");
    }
    match encode_declarations_entry(&key, &map) {
        Ok(bytes) => {
            if let Err(e) = publish(&cached, &bytes) {
                tracing::debug!("not caching built-in shader declarations: {e}");
            }
        }
        Err(e) => tracing::debug!("not caching built-in shader declarations: {e:#}"),
    }
    Ok(map)
}

fn declarations_entry_path(cache_root: &Path, key: &[u8; 32]) -> PathBuf {
    let hex: String = key.iter().map(|b| format!("{b:02x}")).collect();
    cache_root
        .join("builtin-shaders")
        .join(format!("declarations-v{DECLARATIONS_VERSION}"))
        .join(format!("{hex}.bin"))
}

fn encode_declarations_entry(key: &[u8; 32], map: &DeclarationMap) -> Result<Vec<u8>> {
    let payload = postcard::to_allocvec(map)?;
    let mut bytes = Vec::with_capacity(payload.len() + 40);
    bytes.extend_from_slice(DECLARATIONS_MAGIC);
    bytes.extend_from_slice(&DECLARATIONS_VERSION.to_le_bytes());
    bytes.extend_from_slice(key);
    bytes.extend_from_slice(&payload);
    Ok(bytes)
}

/// The entry at `path` when it is complete and was written for exactly `key` (None: missing,
/// corrupt, truncated, another version's or another input's; it is then read again and
/// replaced).
fn read_declarations_entry(path: &Path, key: &[u8; 32]) -> Option<DeclarationMap> {
    let bytes = std::fs::read(path).ok()?;
    let rest = bytes.strip_prefix(DECLARATIONS_MAGIC)?;
    let (version, rest) = rest.split_first_chunk::<4>()?;
    if u32::from_le_bytes(*version) != DECLARATIONS_VERSION {
        return None;
    }
    let (stored, payload) = rest.split_first_chunk::<32>()?;
    if stored != key {
        return None;
    }
    // A complete payload decodes to the whole map with no bytes left over.
    match postcard::take_from_bytes::<DeclarationMap>(payload) {
        Ok((map, [])) => Some(map),
        _ => None,
    }
}

/// Distinguishes the temporary files of concurrent writers in one process (with the process id,
/// across processes).
static TEMP_COUNTER: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);

/// Writes `bytes` to `path` atomically: into a temporary file this writer creates exclusively
/// (process id and a per-process counter; `create_new` refuses a file that exists, whoever made
/// it), then renamed over `path`. A reader sees the old entry or the whole new one, never a
/// partial one. On failure only the writer's own temporary file is removed.
fn publish(path: &Path, bytes: &[u8]) -> std::io::Result<()> {
    use std::io::Write as _;
    let dir = path
        .parent()
        .ok_or_else(|| std::io::Error::other("cache entry without a directory"))?;
    std::fs::create_dir_all(dir)?;
    let name = path
        .file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_default();
    let temp = dir.join(format!(
        ".{name}.{}.{}.tmp",
        std::process::id(),
        TEMP_COUNTER.fetch_add(1, std::sync::atomic::Ordering::Relaxed)
    ));
    let mut file = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&temp)?;
    let written = file.write_all(bytes).and_then(|()| file.flush());
    drop(file);
    let written = written.and_then(|()| std::fs::rename(&temp, path));
    if written.is_err() {
        let _ = std::fs::remove_file(&temp);
    }
    written
}

fn tag_pairs(tags: Option<&Value>) -> Vec<(String, String)> {
    seq(tags.and_then(|t| t.get("tags")))
        .iter()
        .map(|t| {
            (
                str_of(t, "first").to_string(),
                str_of(t, "second").to_string(),
            )
        })
        .collect()
}

/// A serialized pass's `m_Type` for a `UsePass` (0: a pass of its own, 2: a `GrabPass`). Its
/// `m_UseName` names the pass (`"Shader/PASS"`); its own state and tags are empty.
const PASS_TYPE_USE: i64 = 1;

/// Replaces every `UsePass` pass by the pass it names, its name and tags, as Unity does when it
/// loads the shader (canonical shaderkeywords builtin.Nature/Terrain/*.passLightModes: the
/// terrain shaders' `UsePass "Hidden/Nature/Terrain/Utilities/PICKING"` and `SELECTION` passes
/// report `Picking` and `SceneSelectionPass`). Names resolve as the renderer's
/// `ShaderIndex::resolve_use_passes` does: the shader by its name, else by its legacy name
/// (`Legacy Shaders/...`), the pass by name in any case, the first in SubShader order, through
/// up to four `UsePass` steps. A pass nothing resolves keeps its target in
/// [`DeclaredPass::use_pass`], so readers can report it unknown instead of tagless.
fn resolve_use_passes(map: &mut DeclarationMap) {
    let read = map.clone();
    for (shader, declarations) in map.iter_mut() {
        for pass in declarations
            .subshaders
            .iter_mut()
            .flat_map(|s| s.passes.iter_mut())
        {
            if pass.use_pass.is_empty() {
                continue;
            }
            match use_pass_target(&read, &pass.use_pass, 0) {
                Some(found) => *pass = found,
                None => tracing::warn!(
                    "built-in shader `{shader}`: UsePass \"{}\" names no pass in Unity's resources",
                    pass.use_pass
                ),
            }
        }
    }
}

/// The pass a `UsePass` target names, itself resolved (None: no shader or pass by that name).
fn use_pass_target(map: &DeclarationMap, target: &str, depth: u32) -> Option<DeclaredPass> {
    let (shader, name) = target.rsplit_once('/')?;
    let declarations = map
        .get(shader)
        .or_else(|| map.get(&format!("Legacy Shaders/{shader}")))?;
    declarations
        .subshaders
        .iter()
        .flat_map(|s| s.passes.iter())
        .find_map(|pass| {
            let pass = if pass.use_pass.is_empty() {
                pass.clone()
            } else if depth < 4 {
                use_pass_target(map, &pass.use_pass, depth + 1)?
            } else {
                return None;
            };
            pass.name.eq_ignore_ascii_case(name).then_some(pass)
        })
}

/// A serialized shader's declarations (`m_ParsedForm`).
fn read_declarations(parsed: &Value) -> Declarations {
    let names = seq(parsed.get("m_KeywordNames"));
    // One byte per keyword: bit 0 local, bit 1 dynamic (hexadecimal in the serialized form).
    let flags = parsed
        .get("m_KeywordFlags")
        .and_then(Value::as_str)
        .unwrap_or("");
    let flag = |i: usize| {
        flags
            .get(i * 2..i * 2 + 2)
            .and_then(|h| u8::from_str_radix(h, 16).ok())
            .unwrap_or(0)
    };
    let keywords = names
        .iter()
        .enumerate()
        .filter_map(|(i, n)| {
            Some(DeclaredKeyword {
                name: n.as_str()?.to_string(),
                local: flag(i) & 1 != 0,
                dynamic: flag(i) & 2 != 0,
            })
        })
        .collect();
    let subshaders = seq(parsed.get("m_SubShaders"))
        .iter()
        .map(|sub| DeclaredSubShader {
            tags: tag_pairs(sub.get("m_Tags")),
            lod: int(sub, "m_LOD").clamp(0, u32::MAX as i64) as u32,
            passes: seq(sub.get("m_Passes"))
                .iter()
                .map(|pass| {
                    let state = pass.get("m_State");
                    let mut tags = tag_pairs(state.and_then(|s| s.get("m_Tags")));
                    for (k, v) in tag_pairs(pass.get("m_Tags")) {
                        if !tags.iter().any(|(t, _)| *t == k) {
                            tags.push((k, v));
                        }
                    }
                    DeclaredPass {
                        name: state.map(|s| str_of(s, "m_Name")).unwrap_or("").to_string(),
                        tags,
                        use_pass: if int(pass, "m_Type") == PASS_TYPE_USE {
                            str_of(pass, "m_UseName").to_string()
                        } else {
                            String::new()
                        },
                    }
                })
                .collect(),
        })
        .collect();
    Declarations {
        subshaders,
        keywords,
        fallback: str_of(parsed, "m_FallbackName").to_string(),
    }
}

